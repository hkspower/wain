"""The drawn icons on النوخذة's own screens, copied from the company page.

nokhatha.html, nizam.html and admin.html labelled their tabs, buttons, chips,
toasts and order rows with emoji: a different typeface, weight and colour on
every platform, and on a phone without a colour-emoji font, an empty box. The
company page solved the same thing with a `<symbol>` sprite; this writes that
sprite into each app page, holding only the icons that page uses.

One drawing per icon. A symbol the company page already has is copied from
index.html's sprite byte for byte, never redrawn. The handful the company page
has no use for (download, print, check, …) are drawn here, on the same 24×24
grid, in the same 1.8 stroke with round caps and joins.

The block sits between two markers and is generated, so it is never edited by
hand:

    python3 design/app_sprite.py           # rewrite the block in each page
    python3 design/app_sprite.py --check   # exit 1 if a page has drifted
"""


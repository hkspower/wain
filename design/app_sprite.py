# A reference is an icon id in quotes or after a '#': href="#i-chart" in the
# markup, "i-chart" in a script that builds a row.
REF = re.compile(r'(?<=["\'#])i-[a-z]+(?:-[a-z]+)*(?=["\'])')


def company_sprite():
    src = (SITE / "index.html").read_text()
    found = {m.group(2): m.group(1) for m in
             re.finditer(r'(<symbol id="(i-[a-z-]+)" viewBox="0 0 24 24">.*?</symbol>)', src, re.S)}
    clash = sorted(set(found) & set(APP_ONLY))
    if clash:
        sys.exit(f"drawn twice — the company sprite already has {clash}; delete them from APP_ONLY")
    return found


def catalogue():
    lib = company_sprite()
    for k, body in APP_ONLY.items():
        lib[k] = f'<symbol id="{k}" viewBox="0 0 24 24">{body}</symbol>'
    return lib


def strip_block(html):
    a, b = html.find(START), html.find(END)
    if a < 0:
        return html, None
    if b < a:
        sys.exit("an icons block opens and never closes")
    return html[:a] + html[b + len(END):], (a, b + len(END))


def block_for(html, lib):
    rest, _ = strip_block(html)
    used = sorted(set(REF.findall(rest)))
    unknown = [u for u in used if u not in lib]
    if unknown:
        sys.exit(f"no sprite draws {unknown}")
    body = "\n".join(f"    {lib[u]}" for u in used)
    return (f'{START}\n  <svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">\n'
            f"{body}\n  </svg>\n  {END}"), used


def build(html, lib):
    block, used = block_for(html, lib)
    a, b = html.find(START), html.find(END)
    if a >= 0:
        return html[:a] + block + html[b + len(END):], used
    m = re.search(r"<body[^>]*>\n", html)
    if not m:
        sys.exit("no <body> to put the sprite after")
    return html[:m.end()] + "  " + block + "\n" + html[m.end():], used


def main():
    check = "--check" in sys.argv
    lib = catalogue()
    drift = []
    for name in PAGES:
        path = SITE / name
        html = path.read_text()
        out, used = build(html, lib)
        if check:
            if out != html:
                drift.append(name)
        else:
            path.write_text(out)
            print(f"  {name}: {len(used)} icons — {' '.join(used)}")
    if check:
        if drift:
            sys.exit(f"icons block out of date in {drift} — run python3 design/app_sprite.py")
        print("app sprites match the company sprite")


if __name__ == "__main__":
    main()

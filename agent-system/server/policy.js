/**
 * يجيب عن بند سياسة.
 * القيمة الحيّة تُقرأ لحظتَها من الإعدادات ولا تُنسخ، ويُقال مصدر كل جزء.
 */
function answer(policy, live) {
  const parts = [policy.text];
  if (policy.live === 'commission' && live?.commission) {
    parts.push(`والمضبوط الآن: ${live.commission}.`);
  }
  return {
    id: policy.id,
    title: policy.title,
    text: parts.join(' '),
    enforced: policy.enforced,
    why_not: policy.why_not || null,
    source: policy.live ? 'الإعدادات وملفّ السياسات' : 'ملفّ السياسات',
  };
}


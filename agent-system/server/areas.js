/**
 * سقف القطع لكل منطقة — فارغ عمدًا.
 *
 * متى وصلكم الجدول الرسمي، ضعوه هنا هكذا: { 'السالمية': 12 }
 * فيضيق التحقّق على تلك المنطقة وحدها، وتبقى البقيّة على المدى الواسع.
 */
const BLOCKS = {};

/** أوسع مدى معقول للقطعة حين لا يوجد سقف معروف للمنطقة */
const BLOCK_MAX = 999;

const GOVERNORATES = Object.keys(AREAS);

/** كل المناطق في قائمة واحدة — للبحث والتحقّق */
const ALL_AREAS = GOVERNORATES.flatMap((g) => AREAS[g]);

/** المنطقة ← محافظتها */
const AREA_TO_GOV = {};
for (const g of GOVERNORATES) for (const a of AREAS[g]) AREA_TO_GOV[a] = g;

/** هل تنتمي هذه المنطقة إلى تلك المحافظة؟ */
function areaBelongsTo(area, governorate) {
  return !!area && AREA_TO_GOV[area] === governorate;
}

/** أعلى رقم قطعة مقبول في منطقة — من الجدول إن وُجد، وإلّا المدى الواسع */
function blockMaxFor(area) {
  return BLOCKS[area] || BLOCK_MAX;
}

/**
 * يبني نصّ العنوان من أجزائه المهيكلة.
 * «السالمية، قطعة ٤، شارع سالم المبارك» — بأرقام عربية كبقية النظام.
 */
function composeAddress({ area, block, street }) {
  const parts = [];
  if (area) parts.push(area);
  if (block) parts.push('قطعة ' + ar.digits(block));
  if (street) parts.push(String(street).trim());
  return parts.join('، ');
}

/**
 * يقرأ رقم القطعة كما كُتب — «٤» و«4» سواء.
 *
 * الموظّف على لوحة مفاتيح عربية يكتب «٤»، والنظام كلّه يعرض «٤»، فمن غير
 * المعقول أن يرفض ما يعرضه. والقاعدة هنا لا في المتصفّح وحده: الطلب قد يأتي
 * من تطبيق أو من تكامل، فيجب أن يقبل الأرقام العربية أينما جاء.
 *
 * يعيد `{ ok: true, block }` أو `{ ok: false, message }` — والرسالة بأرقام
 * عربية كاملةً، لا «بين ١ و999».
 */
function readBlock(raw, area) {
  const max = blockMaxFor(area);
  const block = Number(ar.toLatin(String(raw).trim()));
  if (!Number.isInteger(block) || block < 1 || block > max) {
    return {
      ok: false,
      message: `رقم القطعة في «${area}» يجب أن يكون عددًا صحيحًا بين ١ و${ar.digits(max)}`,
    };
  }
  return { ok: true, block };
}


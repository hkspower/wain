-- ============ admin: read everything, and count stock ============
create or replace function public.admin_variants()
returns table (
  sku text, slug text, name_en text, size text, collection text, garment text,
  stock int, received int, cost_aed numeric, price numeric, grams int, hs_code text
)
language plpgsql stable security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'not_admin' using errcode = '42501';
  end if;
  return query
    select v.sku, v.slug, p.name_en, v.size, v.collection, v.garment,
           v.stock, v.received, v.cost_aed, p.price, v.grams, v.hs_code
      from public.product_variants v
      join public.products p on p.slug = v.slug
     order by v.slug, v.size;
end $$;

revoke all on function public.admin_variants() from public, anon;
grant execute on function public.admin_variants() to authenticated;

-- Counting stock is a single narrow door rather than an UPDATE policy, so the
-- admin can only ever move the count — not the SKU, the cost or the slug.
create or replace function public.admin_set_stock(p_sku text, p_stock int)
returns table (sku text, stock int)
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'not_admin' using errcode = '42501';
  end if;
  if p_stock is null or p_stock < 0 then
    raise exception 'stock_cannot_be_negative' using errcode = 'P0001';
  end if;
  update public.product_variants v
     set stock = p_stock, updated_at = now()
   where v.sku = p_sku;
  if not found then
    raise exception 'sku_not_found' using errcode = 'P0001';
  end if;
  return query select v.sku, v.stock from public.product_variants v where v.sku = p_sku;
end $$;

revoke all on function public.admin_set_stock(text, int) from public, anon;
grant execute on function public.admin_set_stock(text, int) to authenticated;


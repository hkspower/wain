<?php
// Database center: the READ-ONLY database overview behind /backends -> Settings -> "Database center".
// Owner request 2026-11-11: "make backends center database".
//
// Two routes call this file (admin.php, after the administrator gate, GET only):
//
//   db_center     tables (rows, sizes), schema and migration status against the repo's migrations,
//                 backup status, server health (connections, slow queries, lock waits).
//   db_integrity  the integrity checks: orphans and stock against the inventory ledger.
//
// RULES THIS FILE KEEPS (dbcenter-test.mjs asserts each one):
//   * Reads only. No INSERT, UPDATE, DELETE, REPLACE, DDL, LOCK, GRANT, KILL, SET GLOBAL or file
//     access except the one small backup-status file below. The only statement that is not a SELECT
//     or a SHOW is `SET SESSION` of a statement time limit, which changes nothing but this request.
//   * No secret and no row data leaves: counts, table and column NAMES from the repo's own schema or
//     the database's catalogue, sizes, version, numbers. No host, user name, password, database name,
//     file path, SQL text or driver error message. An error is reported as a short code.
//   * No dynamic SQL. Every statement below is a literal string, so the grants derivation
//     (ops/db/make-grants.mjs) sees exactly which tables this file reads; table and column names from
//     information_schema are only ever compared in PHP, never put in a query.
//   * Cheap on shared hosting: one catalogue read for tables, one for columns, a handful of exact
//     counts on indexed tables, and every check query runs under a short statement time limit.
//   * Honest about what it cannot see: a database account without the PROCESS privilege sees only its
//     own connections and no lock waits, and the answer says "unknown" instead of "fine".

declare(strict_types=1);

/** The repo's migration manifest (generated by scripts/make-dbcenter-manifest.mjs), or an empty one. */
function dbcenter_manifest(): array {
    static $m = null;
    if ($m === null) {
        $f = __DIR__ . '/dbcenter-manifest.php';
        $m = is_file($f) ? require $f : null;
        if (!is_array($m) || !isset($m['migrations']) || !is_array($m['migrations'])) $m = ['migrations' => [], 'tables' => []];
    }
    return $m;
}

/** A driver error as a short, safe token: the SQLSTATE and driver code, never the message. */
function dbcenter_err(Throwable $e): string {
    $code = $e instanceof PDOException && is_array($e->errorInfo ?? null) ? (string)($e->errorInfo[1] ?? '') : '';
    return preg_match('/^[0-9]{1,6}$/D', $code) ? 'db_error_' . $code : 'db_error';
}

/** A table or column name this file is willing to print: the catalogue's own spelling, nothing odd. */
function dbcenter_name(mixed $v): string {
    $s = is_string($v) ? $v : '';
    return preg_match('/^[A-Za-z0-9_$]{1,64}$/D', $s) ? $s : '';
}

/**
 * The catalogue of the current database: tables with sizes and every column name.
 * @return array{tables: array<string, array>, columns: array<string, true>}
 */
function dbcenter_catalogue(PDO $db): array {
    $tables = [];
    $q = $db->query("select table_name, engine, table_rows, data_length, index_length, table_collation
                       from information_schema.tables
                      where table_schema = database() and table_type = 'BASE TABLE'
                      order by table_name");
    foreach ($q->fetchAll(PDO::FETCH_NUM) as $r) {
        $name = dbcenter_name($r[0]);
        if ($name === '' || count($tables) >= 500) continue;
        $tables[strtolower($name)] = [
            'name' => $name,
            'engine' => dbcenter_name($r[1]) ?: null,
            'rows_estimate' => $r[2] === null ? null : (int)$r[2],
            'data_bytes' => (int)$r[3],
            'index_bytes' => (int)$r[4],
            'collation' => dbcenter_name($r[5]) ?: null,
        ];
    }
    $columns = [];
    $q = $db->query('select table_name, column_name from information_schema.columns where table_schema = database()');
    foreach ($q->fetchAll(PDO::FETCH_NUM) as $r) {
        $t = dbcenter_name($r[0]); $c = dbcenter_name($r[1]);
        if ($t !== '' && $c !== '') $columns[strtolower($t . '.' . $c)] = true;
        if (count($columns) >= 20000) break;
    }
    return ['tables' => $tables, 'columns' => $columns];
}

/**
 * Which of the repo's migrations does this database carry? A migration is "applied" when every table and
 * column it provides exists, "missing" when none of its tables and columns do, "partial" otherwise.
 * (Presence only: a type or a default that differs is the job of scripts/db-schema-diff.mjs.)
 */
function dbcenter_migrations(array $cat): array {
    $man = dbcenter_manifest();
    $out = [];
    foreach ($man['migrations'] as $file => $m) {
        $mt = is_array($m['tables'] ?? null) ? $m['tables'] : [];
        $mc = is_array($m['columns'] ?? null) ? $m['columns'] : [];
        $missT = []; $missC = []; $have = 0;
        foreach ($mt as $t) { if (isset($cat['tables'][strtolower((string)$t)])) $have++; else $missT[] = (string)$t; }
        foreach ($mc as $c) { if (isset($cat['columns'][strtolower((string)$c)])) $have++; else $missC[] = (string)$c; }
        $total = count($mt) + count($mc);
        $status = $total === 0 ? 'applied' : (!$missT && !$missC ? 'applied' : ($have === 0 ? 'missing' : 'partial'));
        $out[] = [
            'file' => (string)$file,
            'status' => $status,
            'tables' => count($mt),
            'columns' => count($mc),
            'missing_tables' => array_slice($missT, 0, 20),
            'missing_columns' => array_slice($missC, 0, 40),
            'missing_count' => count($missT) + count($missC),
        ];
    }
    return $out;
}

/**
 * Backup status from the small file the backup job's host side may publish. The app cannot (and must not) reach
 * the backup folder: it is root-only and holds the encryption key's neighbours (ops/db/BACKUP.md). A file the
 * host copies to /var/lib/sporta/backup-status (the `last-status` and `last-success` lines, nothing else) is the
 * only thing read here; `db_backup_status_file` in the store config can name another. Nothing else is opened.
 *   last-status   "ok|fail <epoch> <exit code> <reason>"
 *   last-success  "<epoch> sporta-db-YYYYMMDDTHHMMSSZ.sql.gz.enc"
 * @return array{state: string, age_hours: ?float, last_success_at: ?string, last_status: ?string, reason: ?string, file: ?string, note: string}
 */
function dbcenter_backup(array $cfg, ?int $now = null): array {
    $now ??= time();
    $path = isset($cfg['db_backup_status_file']) && is_string($cfg['db_backup_status_file']) && $cfg['db_backup_status_file'] !== ''
        ? $cfg['db_backup_status_file'] : '/var/lib/sporta/backup-status';
    $base = ['state' => 'not_reported', 'age_hours' => null, 'last_success_at' => null, 'last_status' => null, 'reason' => null, 'file' => null,
        'note' => 'The shop cannot see the backup folder (it is private to the server). To show the backup here, the server job copies two lines to a status file the shop may read. Until then this is unknown, not fine.'];
    if (!@is_file($path) || !@is_readable($path)) return $base;
    $raw = @file_get_contents($path, false, null, 0, 2048);
    if (!is_string($raw) || $raw === '') return $base;
    $okAt = null; $file = null; $status = null; $reason = null; $statusAt = null;
    foreach (preg_split('/\r?\n/', $raw) as $line) {
        $line = trim($line);
        if ($line === '') continue;
        if (preg_match('/^([0-9]{9,11}) (sporta-db-[0-9]{8}T[0-9]{6}Z\.sql\.gz\.enc)$/D', $line, $m)) { $okAt = (int)$m[1]; $file = $m[2]; continue; }
        if (preg_match('/^(ok|fail|none) ([0-9]{1,11}) ([0-9]{1,3}) ([a-z_]{1,40})$/D', $line, $m)) { $status = $m[1]; $statusAt = (int)$m[2]; $reason = $m[4]; }
    }
    if ($okAt === null && $status === null) return $base;
    $age = $okAt !== null ? max(0.0, round(($now - $okAt) / 3600, 1)) : null;
    $state = $okAt === null ? 'never' : ($status === 'fail' ? 'failing' : ($age > 36 ? 'stale' : 'ok'));
    return [
        'state' => $state,
        'age_hours' => $age,
        'last_success_at' => $okAt !== null ? gmdate('Y-m-d\TH:i:s\Z', $okAt) : null,
        'last_status' => $status,
        'reason' => $status === 'fail' ? $reason : null,
        'file' => $file,
        'note' => $state === 'ok' ? 'The newest verified backup is less than 36 hours old.'
            : ($state === 'stale' ? 'The newest verified backup is older than 36 hours. The nightly job may not be running.'
            : ($state === 'failing' ? 'The last backup run failed. The newest good copy is the age shown (if any).' : 'No verified backup has been reported yet.')),
    ];
}

/** One read of SHOW STATUS / SHOW VARIABLES restricted to the named rows. */
function dbcenter_show(PDO $db, string $what): array {
    $out = [];
    if ($what === 'status') {
        $rows = $db->query("show global status where variable_name in ('Uptime','Threads_connected','Threads_running','Max_used_connections','Slow_queries','Aborted_connects','Aborted_clients','Innodb_row_lock_current_waits','Innodb_row_lock_waits','Innodb_row_lock_time_avg','Innodb_deadlocks','Questions')");
    } else {
        $rows = $db->query("show global variables where variable_name in ('max_connections','version','innodb_lock_wait_timeout','long_query_time','slow_query_log','character_set_server','collation_server','sql_mode')");
    }
    foreach ($rows->fetchAll(PDO::FETCH_NUM) as $r) {
        $k = strtolower((string)$r[0]);
        $out[$k] = is_string($r[1]) || is_numeric($r[1]) ? (string)$r[1] : '';
    }
    return $out;
}

/** Judge the health numbers. Each indicator: key, label, value, unit, status ok|warn|fail|info|unknown, note. */
function dbcenter_health(array $st, array $va, array $proc): array {
    $n = static fn(array $a, string $k): ?float => isset($a[$k]) && is_numeric($a[$k]) ? (float)$a[$k] : null;
    $ind = [];
    $add = static function (string $key, string $label, mixed $value, string $unit, string $status, string $note) use (&$ind): void {
        $ind[] = ['key' => $key, 'label' => $label, 'value' => $value, 'unit' => $unit, 'status' => $status, 'note' => $note];
    };
    $up = $n($st, 'uptime');
    $add('uptime', 'Server running for', $up === null ? null : round($up / 3600, 1), 'hours', $up === null ? 'unknown' : ($up < 600 ? 'info' : 'ok'),
        $up !== null && $up < 600 ? 'The database restarted a few minutes ago; the counters below start from then.' : 'Counters below are totals since the server started.');
    $conn = $n($st, 'threads_connected'); $max = $n($va, 'max_connections');
    if ($conn === null || $max === null || $max <= 0) $add('connections', 'Connections in use', $conn, 'of ' . ($max === null ? '?' : (string)(int)$max), 'unknown', 'The server did not report its connection limit.');
    else {
        $ratio = $conn / $max;
        $add('connections', 'Connections in use', (int)$conn, 'of ' . (int)$max, $ratio >= 0.95 ? 'fail' : ($ratio >= 0.8 ? 'warn' : 'ok'),
            $ratio >= 0.8 ? 'Close to the limit: new visitors may get an error.' : 'Plenty of room.');
    }
    $run = $n($st, 'threads_running');
    $add('threads_running', 'Statements running now', $run === null ? null : (int)$run, '', $run === null ? 'unknown' : ($run >= 40 ? 'fail' : ($run >= 20 ? 'warn' : 'ok')),
        'A few is normal; a long queue means something is slow.');
    $slow = $n($st, 'slow_queries');
    if ($slow === null) $add('slow_queries', 'Slow statements', null, '', 'unknown', 'Not reported.');
    else {
        $perHour = $up !== null && $up >= 3600 ? $slow / ($up / 3600) : null;
        $lq = $va['long_query_time'] ?? '';
        $add('slow_queries', 'Slow statements since start', (int)$slow, $lq !== '' && is_numeric($lq) ? 'over ' . rtrim(rtrim(number_format((float)$lq, 2, '.', ''), '0'), '.') . ' s' : '',
            $slow === 0.0 ? 'ok' : ($perHour !== null && $perHour > 20 && $slow >= 20 ? 'warn' : 'info'),
            $slow === 0.0 ? 'None counted.' : 'The database counted these itself; the slow log is off, so the statements are not stored.');
    }
    $cw = $n($st, 'innodb_row_lock_current_waits');
    $add('lock_waits_now', 'Statements waiting on a lock now', $cw === null ? null : (int)$cw, '', $cw === null ? 'unknown' : ($cw > 0 ? 'warn' : 'ok'),
        $cw !== null && $cw > 0 ? 'Something is holding a row. If it stays above zero for minutes, a statement is stuck.' : 'Nothing is waiting.');
    $lw = $n($st, 'innodb_row_lock_waits'); $avg = $n($st, 'innodb_row_lock_time_avg');
    $add('lock_waits_total', 'Lock waits since start', $lw === null ? null : (int)$lw, $avg === null ? '' : 'avg ' . (int)$avg . ' ms', $lw === null ? 'unknown' : ($avg !== null && $avg > 1000 && $lw > 10 ? 'warn' : 'ok'),
        'Short waits are normal when two customers touch the same stock row.');
    $dl = $n($st, 'innodb_deadlocks');
    if ($dl !== null) $add('deadlocks', 'Deadlocks since start', (int)$dl, '', $dl > 0 ? 'warn' : 'ok', $dl > 0 ? 'The database cancelled a statement to break a lock cycle. Rare ones are retried.' : 'None.');
    $ab = $n($st, 'aborted_connects');
    if ($ab !== null) $add('aborted_connects', 'Failed connection attempts', (int)$ab, '', $ab > 200 ? 'warn' : 'info', 'Wrong logins, blocked machines or a scan. A sudden climb is worth a look.');
    if ($proc['available']) {
        $lt = (float)$proc['longest_seconds'];
        $add('longest_statement', 'Longest running statement', (int)$lt, 's', $lt > 120 ? 'fail' : ($lt > 30 ? 'warn' : 'ok'),
            $proc['scope'] === 'all' ? 'Across every connection.' : 'Only this account\'s own connections are visible.');
    } else $add('longest_statement', 'Longest running statement', null, '', 'unknown', 'This database account may not list statements.');
    if ($proc['lock_waits'] === null) $add('lock_graph', 'Who is blocking whom', null, '', 'unknown', 'Needs the PROCESS privilege, which the shop\'s account deliberately lacks.');
    else $add('lock_graph', 'Who is blocking whom', (int)$proc['lock_waits'], 'waits', $proc['lock_waits'] > 0 ? 'warn' : 'ok', $proc['lock_waits'] > 0 ? 'At least one statement waits for another.' : 'No statement waits for another, as far as this account can see.');
    return $ind;
}

/** Longest non-idle statement and lock-wait count, as far as this account may see them. */
function dbcenter_processes(PDO $db): array {
    $out = ['available' => false, 'longest_seconds' => 0, 'scope' => 'own', 'lock_waits' => null];
    try {
        $r = $db->query("select count(*), coalesce(max(time), 0) from information_schema.processlist where command <> 'Sleep' and id <> connection_id()")->fetch(PDO::FETCH_NUM);
        $out['available'] = true; $out['longest_seconds'] = (int)($r[1] ?? 0);
    } catch (Throwable $e) { /* not visible */ }
    try {
        $n = (int)$db->query('select count(*) from information_schema.innodb_lock_waits')->fetchColumn();
        $out['lock_waits'] = $n; $out['scope'] = 'all';
    } catch (Throwable $e) { /* needs PROCESS: stays unknown */ }
    return $out;
}

/** Exact counts for the tables the shop is made of: one literal statement each, run only when the table exists. */
function dbcenter_counts(PDO $db, array $cat): array {
    // each entry is a closure around ONE literal statement, so the grants derivation and the column audit read it as written
    $stm = [
        'orders' => static fn() => $db->query('select count(*) from orders'),
        'order_items' => static fn() => $db->query('select count(*) from order_items'),
        'products' => static fn() => $db->query('select count(*) from products'),
        'product_variants' => static fn() => $db->query('select count(*) from product_variants'),
        'inventory_movements' => static fn() => $db->query('select count(*) from inventory_movements'),
        'customer_accounts' => static fn() => $db->query('select count(*) from customer_accounts'),
        'fulfilment_outbox' => static fn() => $db->query('select count(*) from fulfilment_outbox'),
    ];
    $out = [];
    foreach ($stm as $t => $run) {
        if (!isset($cat['tables'][$t])) { $out[$t] = null; continue; }
        try { $out[$t] = (int)$run()->fetchColumn(); } catch (Throwable $e) { $out[$t] = null; }
    }
    return $out;
}

/** The whole overview. $cfg is the store config (only db_backup_status_file is read from it). */
function dbcenter_overview(PDO $db, array $cfg = [], ?int $now = null): array {
    $cat = dbcenter_catalogue($db);
    $man = dbcenter_manifest();
    $repoTables = array_fill_keys(array_map('strtolower', array_map('strval', $man['tables'] ?? [])), true);
    $rows = [];
    $tot = ['tables' => 0, 'rows_estimate' => 0, 'bytes' => 0];
    foreach ($cat['tables'] as $key => $t) {
        $bytes = $t['data_bytes'] + $t['index_bytes'];
        $rows[] = $t + ['total_bytes' => $bytes, 'in_repo' => isset($repoTables[$key])];
        $tot['tables']++; $tot['rows_estimate'] += (int)($t['rows_estimate'] ?? 0); $tot['bytes'] += $bytes;
    }
    usort($rows, static fn($a, $b) => $b['total_bytes'] <=> $a['total_bytes'] ?: strcmp($a['name'], $b['name']));
    $mig = dbcenter_migrations($cat);
    $missingTables = array_values(array_filter(array_keys($repoTables), static fn($t) => !isset($cat['tables'][$t])));
    $extra = array_values(array_map(static fn($r) => $r['name'], array_filter($rows, static fn($r) => !$r['in_repo'])));
    $health = ['status' => [], 'variables' => []];
    $healthErr = null;
    try { $health['status'] = dbcenter_show($db, 'status'); $health['variables'] = dbcenter_show($db, 'variables'); } catch (Throwable $e) { $healthErr = dbcenter_err($e); }
    $proc = dbcenter_processes($db);
    $ver = $health['variables']['version'] ?? '';
    return [
        'generated_at' => gmdate('Y-m-d\TH:i:s\Z', $now ?? time()),
        'server' => [
            'version' => preg_match('/^[0-9A-Za-z.\-+_ ]{1,60}$/D', $ver) ? $ver : null,
            'charset' => dbcenter_name($health['variables']['character_set_server'] ?? '') ?: null,
            'collation' => dbcenter_name($health['variables']['collation_server'] ?? '') ?: null,
        ],
        'totals' => $tot,
        'tables' => $rows,
        'counts' => dbcenter_counts($db, $cat),
        'schema' => [
            'repo_tables' => count($repoTables),
            'missing_tables' => array_slice($missingTables, 0, 40),
            'other_tables' => count($extra),
            'other_table_names' => array_slice($extra, 0, 80),
            'migrations' => $mig,
            'migrations_applied' => count(array_filter($mig, static fn($m) => $m['status'] === 'applied')),
            'migrations_total' => count($mig),
            'manifest' => $man['migrations'] !== [],
        ],
        'backup' => dbcenter_backup($cfg, $now),
        'health' => ['error' => $healthErr, 'indicators' => $healthErr ? [] : dbcenter_health($health['status'], $health['variables'], $proc)],
    ];
}

/** The integrity checks. Each: key, label, severity (fail|warn|info), status (pass|fail|warn|info|skip|unknown), count, detail. */
function dbcenter_integrity(PDO $db): array {
    $cat = dbcenter_catalogue($db);
    $has = static fn(string $t): bool => isset($cat['tables'][$t]);
    $hasCol = static fn(string $t, string $c): bool => isset($cat['columns'][$t . '.' . $c]);
    // A short time limit for this request only (MariaDB: seconds, MySQL: milliseconds). Neither changes any data.
    try { $db->exec('set session max_statement_time = 5'); } catch (Throwable $e) {
        try { $db->exec('set session max_execution_time = 5000'); } catch (Throwable $e2) { /* no limit available */ }
    }
    $checks = [
        ['items_orphan_order', 'Order lines that point at no order', 'fail', ['order_items', 'orders'], [],
            static fn() => $db->query('select count(*) from order_items oi left join orders o on o.id = oi.order_id where o.id is null'),
            'A line with no order cannot be shown or shipped. The foreign key should make this impossible.'],
        ['items_orphan_product', 'Order lines that point at no product', 'fail', ['order_items', 'products'], [],
            static fn() => $db->query('select count(*) from order_items oi left join products p on p.id = oi.product_id where p.id is null'),
            'The order history cannot name the product.'],
        ['orders_without_items', 'Orders with no lines', 'warn', ['orders', 'order_items'], [],
            static fn() => $db->query('select count(*) from orders o where not exists (select 1 from order_items oi where oi.order_id = o.id)'),
            'An order with nothing in it: usually an interrupted checkout.'],
        ['variants_orphan_product', 'Stock rows (sizes) whose product does not exist', 'warn', ['product_variants', 'products'], [],
            static fn() => $db->query('select count(*) from product_variants v left join products p on p.slug = v.slug where p.id is null'),
            'Stock is counted for a product that is gone or was renamed.'],
        ['variants_negative_stock', 'Sizes with negative stock', 'fail', ['product_variants'], [],
            static fn() => $db->query('select count(*) from product_variants where stock < 0'),
            'Stock below zero means more was sold than counted.'],
        ['active_without_variants', 'Shown products with no size rows', 'info', ['products', 'product_variants'], [],
            static fn() => $db->query('select count(*) from products p where p.active = 1 and not exists (select 1 from product_variants v where v.slug = p.slug)'),
            'These products have no stock rows, so the shop cannot say what is in stock.'],
        ['movements_orphan_sku', 'Stock movements for a size that does not exist', 'fail', ['inventory_movements', 'product_variants'], [],
            static fn() => $db->query('select count(*) from inventory_movements m left join product_variants v on v.sku = m.sku where v.sku is null'),
            'The stock history names a size the shop no longer has.'],
        ['stock_vs_ledger', 'Sizes whose stock differs from the last stock movement', 'warn', ['product_variants', 'inventory_movements'], [],
            static fn() => $db->query('select count(*) from product_variants v join inventory_movements m on m.sku = v.sku where m.id = (select max(m2.id) from inventory_movements m2 where m2.sku = v.sku) and m.after_stock <> v.stock'),
            'The count on the shelf and the stock history disagree: a change was made outside the Stock screen, or a sale took stock after the last movement. Open Stock for those sizes and count them.'],
        ['paid_stock_released', 'Paid orders whose stock was put back', 'fail', ['orders'], [['orders', 'stock_released']],
            static fn() => $db->query("select count(*) from orders where payment_status = 'paid' and stock_released = 1"),
            'The customer paid but the garments were counted as available again.'],
        ['stuck_stock_claims', 'Unpaid orders still holding stock after 3 days', 'warn', ['orders'], [['orders', 'stock_claimed'], ['orders', 'stock_released']],
            static fn() => $db->query("select count(*) from orders where payment_status = 'pending' and stock_claimed = 1 and stock_released = 0 and created_at < now() - interval 3 day"),
            'The release job (every 15 minutes) should have put these back.'],
        ['outbox_orphan', 'Warehouse messages for no order', 'fail', ['fulfilment_outbox', 'orders'], [],
            static fn() => $db->query('select count(*) from fulfilment_outbox f left join orders o on o.id = f.order_id where o.id is null'),
            'A message the warehouse could never match to an order.'],
        ['outbox_missing_new', 'Orders of the last 30 days with no warehouse message', 'warn', ['orders', 'fulfilment_outbox'], [],
            static fn() => $db->query("select count(*) from orders o where o.created_at > now() - interval 30 day and not exists (select 1 from fulfilment_outbox f where f.order_id = o.id and f.kind = 'new')"),
            'The warehouse may never have heard of these orders.'],
        ['outbox_stuck', 'Warehouse messages unsent for over an hour', 'warn', ['fulfilment_outbox'], [],
            static fn() => $db->query('select count(*) from fulfilment_outbox where sent_at is null and created_at < now() - interval 1 hour'),
            'The mail job (every 5 minutes) should have sent these. Check the warehouse e-mail setting.'],
    ];
    $out = [];
    $started = microtime(true);
    foreach ($checks as [$key, $label, $sev, $tables, $cols, $run, $why]) {
        $row = ['key' => $key, 'label' => $label, 'severity' => $sev, 'status' => 'skip', 'count' => null, 'detail' => ''];
        $missing = [];
        foreach ($tables as $t) if (!$has($t)) $missing[] = $t;
        foreach ($cols as [$t, $c]) if ($has($t) && !$hasCol($t, $c)) $missing[] = $t . '.' . $c;
        if ($missing) { $row['detail'] = 'Not checked: this database does not have ' . implode(', ', $missing) . ' yet (see Schema).'; $out[] = $row; continue; }
        if (microtime(true) - $started > 20) { $row['detail'] = 'Not checked: the time budget for this screen ran out. Press Run again.'; $out[] = $row; continue; }
        try {
            $n = (int)$run()->fetchColumn();
            $row['count'] = $n;
            $row['status'] = $n === 0 ? 'pass' : ($sev === 'fail' ? 'fail' : ($sev === 'warn' ? 'warn' : 'info'));
            $row['detail'] = $n === 0 ? 'None found.' : $why;
        } catch (Throwable $e) {
            $row['status'] = 'unknown';
            $row['detail'] = 'The check could not run (' . dbcenter_err($e) . ').';
        }
        $out[] = $row;
    }
    try { $db->exec('set session max_statement_time = 0'); } catch (Throwable $e) { try { $db->exec('set session max_execution_time = 0'); } catch (Throwable $e2) { /* none */ } }
    $worst = 'pass';
    foreach ($out as $c) { if ($c['status'] === 'fail') { $worst = 'fail'; break; } if ($c['status'] === 'warn') $worst = 'warn'; elseif ($c['status'] === 'unknown' && $worst === 'pass') $worst = 'unknown'; }
    return ['generated_at' => gmdate('Y-m-d\TH:i:s\Z'), 'overall' => $worst, 'checks' => $out];
}

// Sporta icon set on /backends: builds the ADMINICONS section of addons-src/sporta-admin-knet.css from the hand-drawn glyphs in
// brand/iconset/*.svg and the map in scripts/lib/admin-iconset-rules.mjs.
//
//   node scripts/build-admin-iconset.mjs           write the section into the add-on SOURCE (then run npm run build:addon-css)
//   node scripts/build-admin-iconset.mjs --check   exit 1 if the source's section is not what the glyphs and the map produce
//
// Why a second generator and not another block of the storefront's ICON SET (build-iconset.mjs): that section lives in
// public/sporta-shadows.css, which is scoped to the storefront and must stay byte-identical; the admin's own add-on is the file the
// live admin already loads, and the owner's rule is that /backends is styled by that one stylesheet. The glyph data URIs therefore
// live here, inside the admin add-on, so it does not depend on the storefront sheet (or on a release of it).
// The technique is the storefront's (see build-iconset.mjs): every icon keeps its own <svg> (box, position, transforms, colour);
// its shapes are made invisible and the box is painted in currentColor through a CSS mask that is the new glyph.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ROOT, glyphs, maskSvg, uri, TIERS } from './build-iconset.mjs'
import { BASE, REFINE, MIRROR, GLYPHS } from './lib/admin-iconset-rules.mjs'

export const SRC = join(ROOT, 'addons-src', 'sporta-admin-knet.css')
export const START = '/* ==== ADMINICONS'
export const END = '/* ==== end ADMINICONS */'
export const NEXT = '/* ==== SIZES:'   // new sections go BEFORE this one (sizes-admin-test checks it is last)

export const section = () => {
  const G = glyphs()
  for (const n of GLYPHS) if (!G[n]) throw new Error(`no source for glyph "${n}" in brand/iconset`)
  const L = []
  L.push(`${START} (2026-11-11, owner: "fix backends with frontends", look part) ===============================================
 * The admin's icons are the storefront's: one Sporta icon set (brand/iconset/*.svg). GENERATED by scripts/build-admin-iconset.mjs from
 * those sources and from the map in scripts/lib/admin-iconset-rules.mjs; edit those, run the script, then npm run build:addon-css. Never
 * edit this section by hand (npm run test:admin-iconset fails when it drifts).
 *
 * The compiled admin has no source here, so each of its inline icons is recognised by the exact shape data of the build and keeps its
 * own <svg> (box, position, transforms, colour: the nav item's terracotta when active, slate when not, its hover colour). Its shapes
 * are hidden and the box is painted in currentColor through a mask that is the Sporta glyph: nothing in the markup changes, nothing
 * moves, and taking this section out restores the old icons exactly. The line is ${TIERS.sm}px in screen pixels (every admin icon is
 * 16 to 20px; the storefront's 1.75px tier starts at 21px).
 * The build draws several nav items with the same shape (four hearts, two stars, two boxes, two locks, two globes, two plus signs):
 * the REFINEMENTS below tell them apart by a stable neighbour (the Returns item, the Topbar item, the Inventory item, first and last
 * place) so CRM, Support, Profiles, Promotions, Catalogue, Discounts, Payments, Activity and Settings each get their own glyph. If an
 * anchor ever moves, the item keeps the base glyph of its shape: it never loses its icon.
 * ===================================================================================================================== */`)
  L.push('.admin-shell {')
  for (const n of GLYPHS) L.push(`  --sai-${n}: ${uri(maskSvg(G[n], TIERS.sm))};`)
  L.push('}')
  const all = []
  const emit = (title, rules) => {
    L.push(`/* ${title} */`)
    for (const r of rules) {
      L.push(`/* ${r.g}: ${r.where} */`)
      L.push(`${r.sel.join(',\n')} {\n  --sai: var(--sai-${r.g});\n}`)
      all.push(...r.sel)
    }
  }
  emit('base: one glyph per shape the build draws', BASE)
  emit('refinements: more specific, so they win over the base glyph of the same shape', REFINE)
  const ALL = `:is(\n  ${all.join(',\n  ')}\n)`
  L.push('/* the swap: the old shapes are hidden, the box is painted through the new glyph */')
  L.push(`${ALL} {\n  background-color: currentColor;\n  -webkit-mask: var(--sai) center / 100% 100% no-repeat;\n  mask: var(--sai) center / 100% 100% no-repeat;\n}`)
  L.push(`${ALL} > * {\n  visibility: hidden;\n}`)
  L.push('/* direction: the returns U-turn points back in the reading direction (the individual `scale` property composes with any transform) */')
  L.push(`${MIRROR.join(',\n')} {\n  scale: -1 1;\n}`)
  L.push(END)
  return L.join('\n') + '\n'
}

export const splice = (css, sec) => {
  const i = css.indexOf(START), j = css.indexOf(END)
  if (i >= 0) {
    if (j < i) throw new Error('ADMINICONS start marker without its end marker')
    return css.slice(0, i) + sec + css.slice(j + END.length).replace(/^\n/, '')
  }
  const k = css.indexOf(NEXT)
  if (k < 0) throw new Error('the SIZES marker is missing: nowhere to put the section')
  return css.slice(0, k) + sec + '\n' + css.slice(k)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(SRC, 'utf8'), want = splice(css, section())
  if (process.argv.includes('--check')) {
    if (css !== want) { console.error('addons-src/sporta-admin-knet.css ADMINICONS is not what brand/iconset produces: run node scripts/build-admin-iconset.mjs'); process.exit(1) }
    process.exit(0)
  }
  writeFileSync(SRC, want)
  console.log(`ADMINICONS: ${GLYPHS.length} glyphs, ${BASE.length} base + ${REFINE.length} refinements; section ${section().length} bytes`)
}

// Builds supabase/SETUP-ALL.sql — the five migrations, in the one order that
// works, as a single file.
//
//   node scripts/generate-setup-sql.mjs
//
// WHY
// The five files must run in sequence: checkout-migration adds create_order,
// which needs the tables from schema.sql, and seed-products needs the products
// table to exist. Running them out of order, or stopping after two, is the
// single most common way this setup fails — and it fails quietly, with a
// storefront that renders and a checkout that refuses every order.
//
// Concatenating them by hand would go stale the moment one is edited, so this
// generates it from the same files that are the source of truth.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const web = resolve(new URL('..', import.meta.url).pathname)
const dir = join(web, 'supabase')

// Order matters. Do not sort this.
// verify.sql is ALWAYS last — it reports on everything above it, and the whole
// point is that the file ends by telling you whether it worked.
const PARTS = [
  ['schema.sql',            'Tables, row-level security and the public read policy'],
  ['admin-migration.sql',   'Admin reads, order stats and the fulfilment fields'],
  ['checkout-migration.sql','create_order — without this every checkout fails'],
  ['passcode-migration.sql','Admin device quick-unlock'],
  ['payment-method-migration.sql','Cash on delivery alongside KNET'],
  // Must come AFTER payment-method-migration (it reads orders.payment_method)
  // and after admin-migration (it replaces admin_order_stats).
  ['admin-cod-migration.sql','Settling cash orders, and cash-owed in the stats'],
  // LAST of the admin parts: it re-gates every admin policy and RPC created
  // above onto the admin_users allowlist, so it must run after they exist.
  ['admin-allowlist-migration.sql','Admin means allowlisted, not merely signed in'],
  // Needs is_admin() from the allowlist migration.
  ['passcode-hardening-migration.sql','Quick-unlock: admins only, owned, revocable'],
  // After payment-method-migration, whose create_order it replaces.
  ['order-options-migration.sql','Orders record the size and the fit that was chosen'],
  // Needs order_items.size/fit from the file above, and is_admin() from the
  // allowlist migration.
  ['fulfilment-migration.sql','Every order queues a message for the logistics company'],
  // Reads order_items.size/fit and unit_price, so after order-options.
  ['invoice-migration.sql', 'get_order_invoice — the customer\'s printable invoice'],
  ['seed-products.sql',     'The 46 products, and retirement of anything older'],
  // LAST of all: every variant row references a product slug, so the products
  // must exist. Also needs is_admin() from the allowlist migration.
  ['ahed-inventory-migration.sql','AHED sizes and stock, from the packing slip'],
  // Needs is_admin(). A no-op if Storage is not provisioned in the project.
  ['storage-migration.sql','Storage: public read of product images, admin-only writes'],
  ['verify.sql',           'Did it work? — the report this file ends with'],
]

const rule = (s) => `-- ${'='.repeat(74)}\n-- ${s}\n-- ${'='.repeat(74)}`

let out = `-- Sporta — complete Supabase setup, in one file.
--
-- HOW TO RUN
--   Supabase dashboard -> SQL Editor -> New query -> paste all of this -> Run.
--
-- Safe to run again at any time. Every statement is idempotent: tables are
-- created only if missing, policies and functions are replaced, and products
-- match on slug so prices update in place and nothing is duplicated.
--
-- It is ONE file because the parts must run in order, and running them out of
-- order fails silently: the shop still renders, and every checkout is refused.
--
-- The last statement prints a report. Read it — it says what is set up and what
-- is still missing.
--
-- GENERATED by scripts/generate-setup-sql.mjs. Do not hand-edit; change the
-- file it came from and regenerate.

`

for (const [file, what] of PARTS) {
  const body = readFileSync(join(dir, file), 'utf8').trimEnd()
  out += `${rule(`${file} — ${what}`)}\n\n${body}\n\n\n`
}

// The closing report is verify.sql, the last entry in PARTS above. It used to
// be a row of raw counts appended here, which the reader had to interpret —
// "admins_allowlisted: 0" is only meaningful if you already know that an empty
// allowlist locks you out of /admin. verify.sql says that in words, and being a
// real file it can be re-run on its own later.

writeFileSync(join(dir, 'SETUP-ALL.sql'), out)
const lines = out.split('\n').length
console.log(`supabase/SETUP-ALL.sql written — ${PARTS.length} parts, ${lines} lines`)

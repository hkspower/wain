// Writes src/lib/garments.js: slug -> garment, the only AHED field the product
// card needs (to decide whether a fit choice exists). Generated from ahed.js so
// the storefront's first-load chunk never carries the AHED product table.
// Run after scripts/generate-ahed.mjs:  node scripts/generate-garments.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { AHED_PRODUCTS } from '../src/lib/ahed.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'src', 'lib', 'garments.js')
const entries = Object.entries(AHED_PRODUCTS)
  .map(([slug, p]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(p.garment)},`)
  .sort()
const text = `// GARMENT BY SLUG — generated by scripts/generate-garments.mjs from ahed.js.
// Do not hand-edit. Only the garment name, so cards can decide whether a fit
// choice exists without loading the AHED product table.
export const GARMENT_BY_SLUG = {
${entries.join('\n')}
}
`
writeFileSync(out, text)
console.log(`wrote ${entries.length} entries to ${out}`)

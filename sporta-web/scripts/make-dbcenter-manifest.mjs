#!/usr/bin/env node
// make-dbcenter-manifest.mjs — writes dropin/php-store/dbcenter-manifest.php, the list of tables and columns each
// repo migration provides, which the Database center (dbcenter.php) compares with the live catalogue.
//
//   node scripts/make-dbcenter-manifest.mjs            rewrite the file
//   node scripts/make-dbcenter-manifest.mjs --check    exit 1 when the file is not what ops/db/expected-schema.json says
//
// The source is ops/db/expected-schema.json (built from a private MariaDB by scripts/db-schema-diff.mjs: which table
// and column each migration creates). Only files that really sit in dropin/php-store are listed (install.mysql.sql is the
// union of the others, seed.mysql.sql provides nothing) so a migration is reported once. The output is a PHP array of
// names: no SQL, no credentials, nothing to execute. Regenerate it whenever expected-schema.json is rebuilt.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'ops/db/expected-schema.json')
export const OUT = join(ROOT, 'dropin/php-store/dbcenter-manifest.php')
const SKIP = new Set(['install.mysql.sql', 'seed.mysql.sql'])
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

export function build() {
  const d = JSON.parse(readFileSync(SRC, 'utf8'))
  const migs = {}
  for (const [file, items] of Object.entries(d.provides)) {
    if (SKIP.has(file) || file.includes('/') || !existsSync(join(ROOT, 'dropin/php-store', file))) continue
    const tables = [], columns = []
    for (const it of items) {
      const m = /^(table|column):(.+)$/.exec(it)
      if (!m) continue
      ;(m[1] === 'table' ? tables : columns).push(m[2])
    }
    migs[file] = { tables: tables.sort(), columns: columns.sort() }
  }
  const tables = Object.keys(d.tables).sort()
  const lines = ['<?php',
    '// GENERATED by scripts/make-dbcenter-manifest.mjs from ops/db/expected-schema.json. Do not edit by hand:',
    '// `node scripts/make-dbcenter-manifest.mjs` rewrites it, `--check` (and npm run test:db-center) fails when it is stale.',
    '// Names only. dbcenter.php compares these with information_schema to say which migrations a database carries.',
    'return [', "    'tables' => [" + tables.map(q).join(', ') + '],', "    'migrations' => ["]
  for (const f of Object.keys(migs).sort()) {
    lines.push(`        ${q(f)} => [`, `            'tables' => [${migs[f].tables.map(q).join(', ')}],`, `            'columns' => [${migs[f].columns.map(q).join(', ')}],`, '        ],')
  }
  lines.push('    ],', '];', '')
  return lines.join('\n')
}

if (process.argv[1] && process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build()
  if (process.argv.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    if (cur !== text) { console.error('dbcenter-manifest.php is stale: run node scripts/make-dbcenter-manifest.mjs'); process.exit(1) }
    console.log('dbcenter-manifest.php is current')
  } else { writeFileSync(OUT, text); console.log('wrote ' + OUT) }
}

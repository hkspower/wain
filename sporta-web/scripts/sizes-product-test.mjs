    // -- stock line
    ck('the stock line reserves 1.5rem (2.5rem before) and sits .375rem under the chips (.5rem before)', a.stock && near(a.stock.minh, 1.5 * rem, 0.3) && near(a.stock.mt, .375 * rem, 0.3) && near(b.stock.minh, 2.5 * rem, 0.3) && near(b.stock.mt, .5 * rem, 0.3), `${tag}: ${a.stock && a.stock.minh}/${a.stock && a.stock.mt}`)
    if (sc === 'full-sold') ck('a one-line "only 2 left" fits the reserve (nothing moves when it arrives)', a.stock.kids === 1 && near(a.stock.h, 1.5 * rem, 0.6), `${tag}: ${f1(a.stock.h)} (${a.stock.kids} line)`)
    // -- hint: the bundle's copy stays; only its distance from the chips changes
    if (a.hint) ck('the hint stays, .375rem under the chips (.625rem before)', a.hint.disp !== 'none' && b.hint && b.hint.disp !== 'none' && near(a.hint.mt, .375 * rem, 0.3) && near(b.hint.mt, .625 * rem, 0.3), `${tag}: ${a.hint.disp} ${a.hint.mt}`)
    if (sc === 'one' || sc === 'two' || sc === 'three') ck('the size card has its hint (struck sizes are not carried) as before', !!a.hint && !!b.hint, tag)
    if (sc.startsWith('full')) ck('no hint on a full ladder (as before)', !a.hint && !b.hint, tag)
    // -- fit group and swatches are not stretched into the ladder's grid
    if (a.fit && b.fit) ck('the Fit group keeps its natural chip widths and wraps as before, only the gap is .375rem', a.fit.chips.length === b.fit.chips.length && a.fit.chips.every((c, i) => near(c.w, b.fit.chips[i].w, 0.6) && near(c.h, b.fit.chips[i].h, 0.3)) && a.fit.disp === 'flex' && near(parseFloat(a.fit.gap), .375 * rem, 0.3), `${tag}: ${a.fit.disp} ${a.fit.gap}`)

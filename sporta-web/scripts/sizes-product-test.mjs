const REAL = FILES['sporta-product-fix.css'].split('/* ==== LAYOUT:')[0]
const { before: BEFORE_CSS, section: SECTION } = sectionOf(REAL)
const AFTER_CSS = process.env.ADDON_FILE ? readFileSync(process.env.ADDON_FILE, 'utf8') : REAL
const BLOCKS = blocksOf(SECTION)

let pass = 0, fail = 0
const is = (ok, msg, detail = '') => { if (ok) { pass++ } else { fail++; console.log('FAIL ' + msg + (detail ? '  - ' + detail : '')) } }
const head = (t) => console.log(`\n=== ${t} ${'='.repeat(Math.max(0, 70 - t.length))}`)

// ---- variants of the product-fix file -----------------------------------------------------------------------------
const variants = { before: BEFORE_CSS, after: AFTER_CSS, blank: '', early: BEFORE_CSS }
const mutants = []

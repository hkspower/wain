    if (a.cards.length > 1) ck('cards are .5rem apart (.75rem before)', a.cards.every((c, i) => i === a.cards.length - 1 || near(a.cards[i + 1].y - (c.y + c.h), .5 * rem, 0.6)) && b.cards.every((c, i) => i === b.cards.length - 1 || near(b.cards[i + 1].y - (c.y + c.h), .75 * rem, 0.6)), `${tag}`)
    ck('the card keeps its border, corner and background', a.cardCs.bw === b.cardCs.bw && a.cardCs.bg === b.cardCs.bg && a.cardCs.bc === b.cardCs.bc && a.cardCs.bsty === b.cardCs.bsty, tag)

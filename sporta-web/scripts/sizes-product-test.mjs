// ---- interaction, dark theme, synthetic ladders ----------------------------------------------------------------------
const ratio = () => {
  const cvs = document.createElement('canvas'); cvs.width = cvs.height = 1
  const ctx = cvs.getContext('2d', { willReadFrequently: true })
  const px = (layers) => { ctx.clearRect(0, 0, 1, 1); ctx.fillStyle = '#ffffff'; ctx.fillRect(0, 0, 1, 1); for (const c of layers) { if (!c || c === 'transparent') continue; ctx.fillStyle = c; ctx.fillRect(0, 0, 1, 1) } return [...ctx.getImageData(0, 0, 1, 1).data.slice(0, 3)] }
  const lum = ([r, g, b]) => { const f = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4 }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b) }
  const back = (el) => { const L = []; for (let e = el; e; e = e.parentElement) { const bg = getComputedStyle(e).backgroundColor; if (bg && bg !== 'rgba(0, 0, 0, 0)' && bg !== 'transparent') L.unshift(bg) } return L }
  return [...document.querySelectorAll('#product-size-options [role="group"] > button')].filter((b) => getComputedStyle(b).display !== 'none').map((b) => {
    const bg = px(back(b)), fg = px([...back(b), getComputedStyle(b).color])
    const [x, y] = [lum(fg), lum(bg)].sort((p, q) => q - p)
    return { t: b.textContent.trim(), state: b.disabled ? 'sold-out' : b.getAttribute('aria-pressed') === 'true' ? 'selected' : 'default', ratio: (x + 0.05) / (y + 0.05) }
  })
}
head('colours: every state in light and dark, before and after')

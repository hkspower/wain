const openPage = async (url, w, lang, h = 844) => {
  const ctx = await browser.newContext({ viewport: { width: w, height: h }, locale: lang === 'ar' ? 'ar-KW' : 'en-US' })
  const pg = await ctx.newPage()
  await pg.goto(base + url, { waitUntil: 'load' })
  await pg.evaluate(() => document.fonts.ready)
  await pg.waitForTimeout(60)
  await pg.evaluate(() => document.fonts.ready)
  return { pg, ctx }
}
const setVariant = (pg, v) => pg.evaluate(SETSTYLE, v === 'early' ? [BEFORE_CSS, SECTION] : [variants[v], ''])


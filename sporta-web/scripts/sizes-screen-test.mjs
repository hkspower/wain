// "Reduce sizes", lane B (text and elements on screen): the SIZES sections of four add-on stylesheets, proven on the
// live storefront's markup and rules.
//
//   npm run test:sizes-screen      (rig-free: committed fixtures of the LIVE rendered pages, the live compiled rules,
//                                   the real add-on files, the real self-hosted fonts; no server, database or dist/)
//
// The sections, each the last thing in its file, and what they shrink (numbers are Arabic, 390px, measured on the live build):
//   public/sporta-cat-tiles.css        [sizes-home-N]   category tiles 227 -> 197px, brand strip 150 -> 126px, and from 768px the
//                                                       section headings and tile titles one step down
//   public/sporta-checkout-a11y.css    [sizes-foot-N]   the footer (on every page) 1063 -> 879px; [sizes-title-1] checkout/bag title
//   public/sporta-cart-drawer.css      [sizes-drawer-N] the bag drawer's header, lines and footer
//   public/sporta-returns-touch.css    [sizes-edit-N]   the editorial pages' heading, /about's padding and FAQ rows
// The hero, the header and the product cards are NOT touched (the hero's height is the admin's slider-size setting, held in
// --hero-h from before the first paint).
//
// Pages (scripts/fixtures/sizes-screen, regenerated by scripts/make-sizes-fixtures.mjs): home, about, terms, cart, checkout and
// the open bag drawer, in Arabic (RTL, the default) and English, at 320, 360, 390, 768 and 1280px: 60 page/width/language cases,
// each measured WITHOUT the sections (the four files cut at their SIZES marker) and WITH them. Asserted:
//   page height     home -326px at 390px, never taller on any page, footer -184px on a phone (-95px from 768px up)
//   floors          nothing overflows sideways; no text gets smaller except a heading, and none under 24px; no text under 14px
//                   that was not under 14px; no tap target (a, button, summary, field) loses any of its size below 44px; the
//                   footer links, the social buttons, the club buttons, the brand chips and the drawer controls are 44px or more
//   colours         every text element keeps its colour and its background (no contrast can change)
//   hero            the hero's box, --hero-h and the header's height are identical before and after (first paint and CLS)
//   load order      the same measurements with the sections placed BEFORE the bundle's own rules (every rule wins by specificity)
//   no JavaScript   the footer's call button is added by a script after load: with and without it the footer is the same height
//                   at 360px and wider (and grows by at most one row at 320px); the sections name no script-built node
//   scope and style the sections are last in their files, scoped to .campaign-home / .storefront-root / .campaign-cart-drawer,
//                   use logical properties only, declare no colour, no transition, no url(), no hero rule, and use !important once
//   MUTATION        cutting every section makes the suite fail (count printed); cutting each numbered block on its own fails at
//                   least one check, so no block is dead weight
// Env: CHROMIUM_PATH (default /opt/pw-browsers/chromium).
import { chromium } from 'playwright'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, ADDON_ORDER, SIZES_FILES, SECTION_START, PAGES, WIDTHS, LANGS, sectionOf, blocksOf, addonFiles, serve, measure } from './lib/sizes-screen-page.mjs'

const FILES = addonFiles()
const PARTS = Object.fromEntries(SIZES_FILES.map((f) => [f, sectionOf(FILES[f])]))
const BLOCKS = { 'sporta-cat-tiles.css': ['sizes-home-1', 'sizes-home-2', 'sizes-home-3'], 'sporta-checkout-a11y.css': ['sizes-foot-1', 'sizes-foot-2', 'sizes-title-1'], 'sporta-cart-drawer.css': ['sizes-drawer-1', 'sizes-drawer-2', 'sizes-drawer-3'], 'sporta-returns-touch.css': ['sizes-edit-1', 'sizes-edit-2', 'sizes-edit-3'] }

// ---- variants: the files as shipped, the files without the sections, and one mutant per block -------------------------
const variants = { after: {}, before: Object.fromEntries(SIZES_FILES.map((f) => [f, PARTS[f].before])) }
const mutants = []
for (const f of SIZES_FILES) {
  const blocks = blocksOf(PARTS[f].section)
  for (const b of blocks) {
    const name = `${f} ${b.id}`
    variants[name] = { [f]: PARTS[f].before + PARTS[f].section.slice(0, b.start) + PARTS[f].section.slice(b.end) }
    mutants.push(name)
  }
}
// 'early': the four files without their sections, and the sections themselves in a <style> placed BEFORE the bundle's own
// rules (what a different link order would do): every rule must win by specificity, not by being last
const EARLY = SIZES_FILES.map((f) => PARTS[f].section).join('\n')
variants.early = Object.fromEntries(SIZES_FILES.map((f) => [f, PARTS[f].before]))

// ---- measurement matrix ----------------------------------------------------------------------------------------------
const ref = { current: FILES }
const { server, base } = await serve(ref)
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium' })
const M = {}                   // M[variant]["page|lang|w"] = measurement
const NOCALL = {}              // footer measured without the script-built call button (after only)
const key = (p, l, w) => `${p}|${l}|${w}`
const SETSTYLE = ([name, css]) => { document.querySelector(`style[data-addon="${name}"]`).textContent = css }
for (const lang of LANGS) for (const p of PAGES) for (const w of WIDTHS) {
  const ctx = await browser.newContext({ viewport: { width: w, height: 900 }, locale: lang === 'ar' ? 'ar-KW' : 'en-US' })
  const pg = await ctx.newPage()
  await pg.goto(`${base}/__fx/${p}-${lang}`, { waitUntil: 'load' })
  await pg.evaluate(() => document.fonts.ready)
  await pg.waitForTimeout(60)
  await pg.evaluate(() => document.fonts.ready)
  const order = ['before', 'after', 'early', ...mutants]
  for (const v of order) {
    for (const f of SIZES_FILES) await pg.evaluate(SETSTYLE, [f, (variants[v][f] ?? FILES[f])])
    await pg.evaluate((css) => { let el = document.getElementById('fx-early'); if (!el) { el = document.createElement('style'); el.id = 'fx-early'; document.head.insertBefore(el, document.getElementById('fx-head')) } el.textContent = css }, v === 'early' ? EARLY : '')
    ;(M[v] ||= {})[key(p, lang, w)] = await pg.evaluate(measure)
    if (v === 'after' && p === 'home') {
      NOCALL[key(p, lang, w)] = await pg.evaluate(() => {
        const el = document.getElementById('sporta-footer-call'); if (!el) return null
        const parent = el.parentElement, next = el.nextSibling; el.remove()
        const h = document.querySelector('footer.app-footer').getBoundingClientRect().height
        parent.insertBefore(el, next); return h
      })
    }
  }
  await ctx.close()
}

// ---- assertions ---------------------------------------------------------------------------------------------------------
const near = (a, b, t) => Math.abs(a - b) <= t
const f1 = (n) => (n == null ? 'n/a' : (Math.round(n * 10) / 10).toString())
const HEADING = /^h[1-6]$/
// every check is evaluated per case and recorded as [name, ok, detail]; a name is printed once with its pass count
const run = (B, A, noCall) => {
  const rows = []
  const is = (name, ok, detail = '') => rows.push([name, !!ok, detail])
  for (const lang of LANGS) for (const p of PAGES) for (const w of WIDTHS) {
    const k = key(p, lang, w), b = B[k], a = A[k], tag = `${p} ${lang} ${w}px`
    const phone = w <= 767, rem = a.rem
    // -- every page
    is('nothing overflows sideways', a.docW <= a.vw && a.dOver <= 0, `${tag}: doc ${a.docW} > ${a.vw}, drawer ${a.dOver}`)
    is('no page or block grows taller', a.page <= b.page + 0.5, `${tag}: ${f1(b.page)} -> ${f1(a.page)}`)
    is('self-hosted fonts loaded (text widths are the live ones)', a.fonts.loaded > 0, tag)
    let textBad = '', under14 = '', colourBad = '', tapBad = ''
    const bt = new Map(b.text.map((t) => [t.i, t]))
    for (const t of a.text) {
      const o = bt.get(t.i); if (!o) continue
      if (t.fs < o.fs - 0.01 && !(HEADING.test(t.tag) && t.fs >= 24)) textBad ||= `${tag}: <${t.tag}> "${t.t}" ${o.fs} -> ${t.fs}`
      if (t.fs < Math.min(o.fs, 14) - 0.01) under14 ||= `${tag}: <${t.tag}> "${t.t}" ${o.fs} -> ${t.fs}`
      if (t.color !== o.color || t.bg !== o.bg) colourBad ||= `${tag}: <${t.tag}> "${t.t}"`
    }
    is('no text shrinks except a heading, and none under 24px', !textBad, textBad)
    is('no text falls under 14px that was not under it already', !under14 && a.text.filter((t) => t.fs < 14).length <= b.text.filter((t) => t.fs < 14).length, under14 || tag)
    is('every text element keeps its colour and background (contrast cannot change)', !colourBad, colourBad)
    const bp = new Map(b.taps.map((t) => [t.i, t]))
    for (const t of a.taps) { const o = bp.get(t.i); if (!o) continue; const need = Math.min(Math.min(o.w, o.h), 44); if (Math.min(t.w, t.h) < need - 0.5) tapBad ||= `${tag}: "${t.t}" ${f1(Math.min(o.w, o.h))} -> ${f1(Math.min(t.w, t.h))}` }
    is('no tap target loses size below 44px', !tapBad && a.taps.filter((t) => Math.min(t.w, t.h) < 43.5).length <= b.taps.filter((t) => Math.min(t.w, t.h) < 43.5).length, tapBad || tag)
    if (a.b.header) is('the sticky header is untouched', near(a.b.header.h, b.b.header.h, 0.01) && near(a.b.header.y, b.b.header.y, 0.01), tag)

    // -- the footer (every page that has one)
    if (a.b.footer) {
      const drop = b.b.footer.h - a.b.footer.h, need = { 320: 110, 360: 170, 390: 170, 768: 85, 1280: 90 }[w]
      is(`the footer is shorter (phone -170px, 320px -110px, 768px up -85px)`, drop >= need, `${tag}: -${f1(drop)} (need ${need})`)
      is('footer links, social buttons and club buttons are 44px or more', a.b.linkItems.every((r) => r.h >= 43.5) && a.b.socials.every((r) => r.h >= 43.5 && r.w >= 43.5) && a.b.clubBtns.every((r) => r.h >= 43.5), tag)
      const inner = a.b.inner, btns = a.b.clubBtns
      const inside = btns.every((r) => r.x >= inner.x - 0.5 && r.r <= inner.r + 0.5)
      let overlap = false
      for (let i = 0; i < btns.length; i++) for (let j = i + 1; j < btns.length; j++) if (btns[i].x < btns[j].r - 0.5 && btns[j].x < btns[i].r - 0.5 && btns[i].y < btns[j].b - 0.5 && btns[j].y < btns[i].b - 0.5) overlap = true
      is('the club buttons stay inside the footer and never overlap', inside && !overlap, tag)
      if (phone && btns.length === 2 && w >= 360) is('the two club buttons share one row from 360px', near(btns[0].y, btns[1].y, 1.5), `${tag}: ${f1(btns[0].y)} / ${f1(btns[1].y)}`)
      is('the club copy keeps the full row, the buttons sit under it', a.b.clubCopy.b <= Math.min(...btns.map((r) => r.y)) + 0.5 && a.b.clubCopy.w >= inner.w - inner.w * 0.5 || !phone, tag)
      if (p === 'home' && noCall && noCall[k] != null) {
        const grow = a.b.footer.h - noCall[k]
        is('the script-built call button adds no footer height from 360px (320px: at most one row)', w >= 360 ? grow <= 1 : grow <= 64, `${tag}: +${f1(grow)}`)
      }
      const innerPad = a.p.inner.t
      is('footer container padding: 2rem on a phone, 2.25rem from 768px', near(innerPad, (phone ? 2 : 2.25) * rem, 0.6), `${tag}: ${f1(innerPad)}`)
    }

    // -- the home page
    if (p === 'home') {
      const drop = b.page - a.page, need = { 320: 280, 360: 280, 390: 300, 768: 85, 1280: 95 }[w]
      is('home page height: -300px at 390px (-280px at 320/360px, -85px at 768px, -95px at 1280px)', drop >= need, `${tag}: -${f1(drop)} (need ${need})`)
      is('the hero box, --hero-h and everything above the hero are identical (first paint, CLS)', near(a.b.hero.y, b.b.hero.y, 0.01) && near(a.b.hero.h, b.b.hero.h, 0.01) && a.p.heroH === b.p.heroH && near(a.b.brandBar.y, b.b.brandBar.y, 0.01), `${tag}: hero ${f1(b.b.hero.h)} -> ${f1(a.b.hero.h)}`)
      if (phone) {
        const tb = b.b.tiles.reduce((s, r) => s + r.h, 0), ta = a.b.tiles.reduce((s, r) => s + r.h, 0)
        is('phone: the four category tiles are 100px or more shorter in all', tb - ta >= 100, `${tag}: ${f1(tb)} -> ${f1(ta)}`)
        const floor = Math.min(Math.max(11 * 16, (a.vw - 32) * 0.55), 17 * 16)
        is('phone: every tile keeps the 11rem / .55-of-width floor, and its copy fits inside it', a.b.tiles.every((r, i) => r.h >= floor - 1 && a.b.tileClip[i] <= 1 && a.b.tileCopy[i].y >= r.y - 0.5 && a.b.tileCopy[i].b <= r.b + 0.5), `${tag}: ${a.b.tiles.map((r) => f1(r.h)).join('/')} floor ${f1(floor)}`)
        is('phone: the tiles are never taller than before', a.b.tiles.every((r, i) => r.h <= b.b.tiles[i].h + 0.5), tag)
        is('phone: brand strip at least 20px shorter, chips 56px (44px minimum), 44px heading row', b.b.brandBar.h - a.b.brandBar.h >= 20 && a.b.brandItems.every((r) => near(r.h, 56, 0.6) && r.w >= 44) && a.b.brandHead.h >= 43.5, `${tag}: ${f1(b.b.brandBar.h)} -> ${f1(a.b.brandBar.h)}`)
        is('phone: section heading and tile title keep the live sizes', a.f.sectionH2 === b.f.sectionH2 && a.f.tileTitle === b.f.tileTitle, `${tag}: ${a.f.sectionH2}/${b.f.sectionH2} ${a.f.tileTitle}/${b.f.tileTitle}`)
      } else {
        is('768px up: tiles, rows and brand strip keep their boxes', a.b.tiles.every((r, i) => near(r.h, b.b.tiles[i].h, 0.01) && near(r.y, b.b.tiles[i].y, 0.01)) && near(a.b.brandBar.h, b.b.brandBar.h, 0.01), tag)
        is('768px up: section headings and tile titles one step down, none under 24px / 26px', a.f.sectionH2 <= b.f.sectionH2 + 0.01 && a.f.sectionH2 >= 24 && a.f.tileTitle <= b.f.tileTitle + 0.01 && a.f.tileTitle >= 26 && (w < 1280 || (near(a.f.sectionH2, a.f.featuresH2, 0.6) && a.f.sectionH2 < b.f.sectionH2 - 5 && a.f.tileTitle < b.f.tileTitle - 5)), `${tag}: h2 ${b.f.sectionH2} -> ${a.f.sectionH2} (features ${a.f.featuresH2}), title ${b.f.tileTitle} -> ${a.f.tileTitle}`)
      }
    }

    // -- the bag drawer
    if (p === 'drawer') {
      const tot = (m) => m.b.dHead.h + m.b.dLines.reduce((s, r) => s + r.h, 0) + m.b.dFoot.h
      is('drawer: header, two lines and footer are 40px or more shorter in all', tot(b) - tot(a) >= 40, `${tag}: ${f1(tot(b))} -> ${f1(tot(a))}`)
      is('drawer: the 44px close button has 8px above and below it', a.b.dHead.h >= a.b.dClose.h + 16 - 0.5 && a.b.dClose.h >= 43.5, `${tag}: header ${f1(a.b.dHead.h)}, close ${f1(a.b.dClose.h)}`)
      is('drawer: every line is shorter and no control is under 44px', a.b.dLines.every((r, i) => r.h < b.b.dLines[i].h - 8) && a.taps.every((t) => Math.min(t.w, t.h) >= 43.5), `${tag}: ${a.b.dLines.map((r) => f1(r.h)).join('/')} vs ${b.b.dLines.map((r) => f1(r.h)).join('/')}`)
    }

    // -- editorial pages
    if (p === 'about' || p === 'terms') {
      is('editorial heading: 28px or more on a phone, one step down, never under 28px', a.f.pageH1 >= 28 - 0.01 && a.f.pageH1 <= b.f.pageH1 + 0.01 && (w !== 1280 || a.f.pageH1 < b.f.pageH1 - 10), `${tag}: ${b.f.pageH1} -> ${a.f.pageH1}`)
    }
    if (p === 'about') {
      const drop = b.page - a.page, need = { 320: 200, 360: 250, 390: 250, 768: 160, 1280: 230 }[w]
      is('about page height: -250px on a phone (-200px at 320px), -160px at 768px, -230px at 1280px', drop >= need, `${tag}: -${f1(drop)} (need ${need})`)
      is('about: the page padding follows clamp(2.5rem, 4vw, 3.5rem)', near(a.p.editorial.t, Math.min(Math.max(2.5 * rem, a.vw * 0.04), 3.5 * rem), 0.6), `${tag}: ${f1(a.p.editorial.t)}`)
      is('about: FAQ items are 8px shorter, their 44px summary rows untouched', a.b.faq.every((r, i) => near(b.b.faq[i].h - r.h, 8, 1.5)) && a.b.faqSum.every((r, i) => near(r.h, b.b.faqSum[i].h, 0.01) && r.h >= 43.5), `${tag}: ${a.b.faq.map((r) => f1(r.h)).join('/')} vs ${b.b.faq.map((r) => f1(r.h)).join('/')}`)
    }
    if (p === 'terms') is('terms: the policy pages keep their own padding rhythm', near(a.p.editorial.t, b.p.editorial.t, 0.01) && near(a.p.editorial.b, b.p.editorial.b, 0.01), `${tag}: ${f1(b.p.editorial.t)} -> ${f1(a.p.editorial.t)}`)

    // -- checkout and bag titles
    if (p === 'checkout' || p === 'cart') {
      const h = p === 'checkout' ? 'flowH1' : 'cartH1'
      is('checkout and bag title: 24px at most phone widths, one step down on a desktop, never under 24px', a.f[h] >= 24 - 0.01 && a.f[h] <= b.f[h] + 0.01 && (w !== 1280 || a.f[h] < b.f[h] - 8), `${tag}: ${b.f[h]} -> ${a.f[h]}`)
      if (p === 'checkout') is('checkout title: 1rem above, .5rem below', near(a.p.flowH1.mt, rem, 0.6) && near(a.p.flowH1.mb, 0.5 * rem, 0.6), `${tag}: ${f1(a.p.flowH1.mt)} / ${f1(a.p.flowH1.mb)}`)
    }
  }
  return rows
}

// the same geometry with the sections placed before the bundle's rules

// api/install.mysql.sql — the one-file database install, against real MariaDB.
//
//   npm run test:install-sql
//
// This file is what the owner actually imports. It is GENERATED, and a
// generated artifact nobody verifies is exactly how the hand-made zip in this
// project went stale and carried a payment-losing bug for weeks.
//
// So: build it, import it into an empty database, and assert the result is
// indistinguishable from running the four parts by hand — same tables, same
// columns, same rows. Then import it a second time and assert nothing moved,
// because the instructions promise it is safe to re-run and an owner halfway
// through a broken setup WILL run it again.
import { execFile, execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const run = promisify(execFile)
const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const SQL = join(web, 'dropin/php-store')

let fails = 0
const ok = (n, d = '') => console.log(`ok   ${n}${d ? `  — ${d}` : ''}`)
const bad = (n, d = '') => { fails++; console.log(`FAIL ${n}${d ? `  — ${d}` : ''}`) }
const is = (c, n, d) => (c ? ok(n, d) : bad(n, d))
const head = (t) => console.log(`\n=== ${t} ${'='.repeat(Math.max(0, 54 - t.length))}`)

const mysql = (db, q) => run('mariadb', [db, '-N', '-B', '-e', q]).then((r) => r.stdout.trim())
const importFile = (db, f) =>
  execFileSync('bash', ['-c', `mariadb ${db} < ${JSON.stringify(join(SQL, f))}`], { stdio: 'pipe' })

// Regenerate first: the test must exercise what the build would ship, not a
// copy left on disk from an earlier run.
execFileSync('node', [join(web, 'scripts/make-install-sql.mjs')], { stdio: 'pipe' })

const shape = (db) => mysql(db,
  `select table_name, column_name, column_type, is_nullable, ifnull(column_default,'~')
     from information_schema.columns where table_schema='${db}'
    order by table_name, ordinal_position`)
const counts = (db) => mysql(db,
  `select concat((select count(*) from products), '/', (select count(*) from product_variants),
                 '/', (select count(*) from brands), '/', (select count(*) from settings))`)

for (const db of ['sqlinst_one', 'sqlinst_four']) {
  await mysql('', `drop database if exists ${db}; create database ${db}`)
}

head('one import does what four imports do')
{
  importFile('sqlinst_one', 'install.mysql.sql')
  for (const f of ['schema.mysql.sql', 'seed.mysql.sql', 'brands.mysql.sql', 'promo.mysql.sql']) {
    importFile('sqlinst_four', f)
  }
  const [s1, s4] = [await shape('sqlinst_one'), await shape('sqlinst_four')]
  // Table names carry the schema name; normalise before comparing.
  is(s1 === s4, 'every table and column is identical to the by-hand order',
     s1 === s4 ? `${s1.split('\n').length} columns` : 'schemas differ')
  const [c1, c4] = [await counts('sqlinst_one'), await counts('sqlinst_four')]
  is(c1 === c4, 'and so is every seeded row', `${c1} vs ${c4}`)
  is(c1.startsWith('46/'), 'the catalogue actually loaded', c1)
}

head('it is safe to re-run, which the instructions promise')
{
  const before = await counts('sqlinst_one')
  importFile('sqlinst_one', 'install.mysql.sql')
  const after = await counts('sqlinst_one')
  is(before === after, 'a second import changes no rows', `${before} -> ${after}`)

  // The one that would hurt: an owner re-running this after taking orders.
  await mysql('sqlinst_one', `insert into orders (track_id, amount, subtotal, payment_method, payment_status)
                              values ('SPKEEPME', 9.000, 9.000, 'knet', 'paid')`)
  importFile('sqlinst_one', 'install.mysql.sql')
  is(await mysql('sqlinst_one', "select payment_status from orders where track_id='SPKEEPME'") === 'paid',
     'and a PAID ORDER survives it untouched')
}

head('the concatenation stays legal')
{
  const sql = readFileSync(join(SQL, 'install.mysql.sql'), 'utf8')
  // Each of these would break a phpMyAdmin import, or assume a database name
  // that differs on every Hostinger account.
  for (const [re, what] of [
    [/^\s*delimiter\b/im, 'DELIMITER'],
    [/create\s+(procedure|function|trigger)\b/i, 'a stored routine'],
    [/^\s*use\s+`?\w/im, 'a USE statement'],
    [/create\s+database\b/i, 'CREATE DATABASE'],
  ]) is(!re.test(sql), `no ${what}`)
  is(sql.includes('GENERATED by scripts/make-install-sql.mjs'),
     'and it says it is generated, so nobody edits it by hand')
}

for (const db of ['sqlinst_one', 'sqlinst_four']) await mysql('', `drop database ${db}`)

console.log(fails ? `\n${fails} problem(s) in the one-file install`
                  : '\ninstall.mysql.sql: one import, same result, safe twice')
process.exit(fails ? 1 : 0)

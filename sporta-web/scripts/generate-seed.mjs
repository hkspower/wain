// Regenerates supabase/seed-products.sql from the catalogue.
//
// sporta-html5/assets/products.js is the single source of truth for products
// (the React app imports the same list). Hand-maintaining a second copy in SQL
// is how prices drift between what the site shows and what the customer is
// charged — and the database price is the one that wins at checkout.
//
//   node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const web = join(root, 'sporta-web')

const sandbox = { window: {} }
new Function('window', readFileSync(join(root, 'sporta-html5', 'assets', 'products.js'), 'utf8'))(sandbox.window)
const PRODUCTS = sandbox.window.SPORTA_PRODUCTS
if (!PRODUCTS?.length) throw new Error('catalogue not found')

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

// The bundled artwork is a data: URI — thousands of characters of inline SVG,
// and a placeholder rather than a photograph. It is deliberately not seeded;
// the column is left for real photo URLs.
const rows = PRODUCTS.map((p) =>
  `  (${q(p.slug)}, ${q(p.name.en)}, ${q(p.name.ar)}, ${q(p.desc?.en)}, ${q(p.desc?.ar)}, ` +
  `${Number(p.price).toFixed(3)}, ${q(p.category)}, true)`,
).join(',\n')

const sql = `-- Sporta — product catalogue.
--
-- GENERATED by scripts/generate-seed.mjs from sporta-html5/assets/products.js.
-- Do not hand-edit: change the catalogue and regenerate, or the site will show
-- one price while the database charges another. The database price is the one
-- that wins — create_order reads it and the browser never sends a price.
--
-- Safe to re-run. Matching is on slug, so re-running updates prices and names
-- in place and never duplicates a product.
--
-- ${PRODUCTS.length} products. Generated from the catalogue, not typed by hand.

insert into public.products
  (slug, name_en, name_ar, desc_en, desc_ar, price, category, active)
values
${rows}
on conflict (slug) do update set
  name_en  = excluded.name_en,
  name_ar  = excluded.name_ar,
  desc_en  = excluded.desc_en,
  desc_ar  = excluded.desc_ar,
  price    = excluded.price,
  category = excluded.category,
  active   = excluded.active,
  -- Never clobber a real photo URL with the placeholder's NULL. Once a product
  -- has artwork, re-running the seed leaves it alone.
  image    = coalesce(public.products.image, excluded.image);

-- What the catalogue now looks like to checkout.
select count(*) filter (where active) as active_products,
       min(price) as cheapest, max(price) as dearest
from public.products;
`

writeFileSync(join(web, 'supabase', 'seed-products.sql'), sql)
console.log(`seed-products.sql regenerated — ${PRODUCTS.length} products`)

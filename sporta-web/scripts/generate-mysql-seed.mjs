// Regenerates dropin/php-store/seed.mysql.sql — the catalogue and the AHED
// variant rows the backend prices and ships from.
//
// Same source of truth, same rule: the catalogue file is where products live,
// and a hand-maintained second copy in SQL is how the site shows one price
// while the database charges another. Change the catalogue, re-run this.
//
//   node scripts/generate-mysql-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const web = join(root, 'sporta-web')

const sandbox = { window: {} }
new Function('window', readFileSync(join(root, 'sporta-html5', 'assets', 'products.js'), 'utf8'))(sandbox.window)
const PRODUCTS = sandbox.window.SPORTA_PRODUCTS
if (!PRODUCTS?.length) throw new Error('catalogue not found')

// The variants come straight from data/ahed.json — the transcription of the
// packing slip, and the same file src/lib/ahed.js is generated from. Reading
// the one source means the shelf and the shop cannot disagree about what
// arrived. (This used to parse them back out of a Postgres migration; that
// database is gone, and one hop fewer is one fewer thing to get wrong.)
const variantRows = JSON.parse(readFileSync(join(web, 'data', 'ahed.json'), 'utf8')).variants
if (!variantRows.length) throw new Error('no variants found in data/ahed.json')

const q = (v) => (v == null || v === '' ? 'null' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`)

const productValues = PRODUCTS.map((p) =>
  `  (${q(p.slug)}, ${q(p.name.en)}, ${q(p.name.ar)}, ${q(p.desc?.en)}, ${q(p.desc?.ar)}, ` +
  `${Number(p.price).toFixed(3)}, ${q(p.category)}, 1)`,
).join(',\n')

const variantValues = variantRows.map(
  (v) => `  ('${v.sku}', '${v.slug}', '${v.size}', ${v.received}, ${v.cost_aed})`,
).join(',\n')

const sql = `-- Sporta native backend — catalogue + inventory seed.
--
-- GENERATED by scripts/generate-mysql-seed.mjs. Do not hand-edit.
-- Import in phpMyAdmin AFTER schema.mysql.sql. Safe to re-run: matching is on
-- slug / sku, so prices and names update in place and nothing duplicates.
-- Stock is NOT overwritten on re-run — the shelf count belongs to the shop,
-- not to this file.

set names utf8mb4;

insert into products (slug, name_en, name_ar, desc_en, desc_ar, price, category, active) values
${productValues}
on duplicate key update
  name_en = values(name_en), name_ar = values(name_ar),
  desc_en = values(desc_en), desc_ar = values(desc_ar),
  price   = values(price),   category = values(category), active = values(active);

insert into product_variants (sku, slug, size, stock, cost_aed) values
${variantValues}
on duplicate key update
  slug = values(slug), size = values(size), cost_aed = values(cost_aed);
  -- stock deliberately NOT updated: re-seeding must not overwrite the count.
`

writeFileSync(join(web, 'dropin', 'php-store', 'seed.mysql.sql'), sql)
console.log(`seed.mysql.sql written — ${PRODUCTS.length} products, ${variantRows.length} variants`)

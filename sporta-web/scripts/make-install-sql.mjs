// Build api/install.mysql.sql — the four SQL files as one, in the right order.
//
//   node scripts/make-install-sql.mjs        (runs inside npm run bundle:php)
//
// WHY
// The install instructions say: import schema, then seed, then brands, then
// promo, IN THAT ORDER, and getting it wrong fails quietly. That is four
// chances to make one mistake, in a phpMyAdmin Import screen, on a phone,
// against a shop that will not take a payment until it is right. Every one of
// those failures looks the same from outside: a site that loads and a
// checkout that refuses.
//
// So the order is decided here, once, by a program — and the owner imports a
// single file. The four originals still ship beside it, because someone
// re-running just the promo tables should not have to re-run the catalogue.
//
// GENERATED, NEVER HAND-ASSEMBLED. Same rule as SPORTA-GO-LIVE.zip, and for
// the same reason: the previous hand-made artifact in this project went stale
// and carried a payment-losing bug for weeks. If a part file changes, this is
// rebuilt from it or it is not shipped at all.
//
// Concatenation is only safe because none of the four contains DELIMITER, a
// stored routine, or a USE/CREATE DATABASE statement — checked below and the
// build fails loudly if that ever stops being true. A USE line in particular
// would be fatal on shared hosting, where the database is named
// u123456789_sporta and nothing may assume otherwise.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = join(web, 'dropin/php-store')

// The order IS the dependency graph. schema creates the tables; seed fills the
// catalogue those tables describe; brands and promo are additive and assume
// both. Nothing here is alphabetical or cosmetic.
const PARTS = [
  ['schema.mysql.sql', 'tables, indexes and constraints'],
  ['seed.mysql.sql', 'the catalogue and its sizes'],
  ['brands.mysql.sql', 'the brands list'],
  ['promo.mysql.sql', 'hero slides, settings, promotions and discounts'],
]

const FORBIDDEN = [
  [/^\s*delimiter\b/im, 'DELIMITER — phpMyAdmin needs it declared per file'],
  [/create\s+(procedure|function|trigger)\b/i, 'a stored routine'],
  [/^\s*use\s+`?\w/im, 'a USE statement — the database name differs per host'],
  [/create\s+database\b/i, 'CREATE DATABASE — hPanel creates it, not this file'],
]

const chunks = [
  `-- Sporta — COMPLETE database install, in one file.
--
-- GENERATED by scripts/make-install-sql.mjs from the four part files that
-- ship beside it. Do not edit this file; edit the part and rebuild.
--
-- HOW TO USE IT
--   hPanel -> Databases -> phpMyAdmin -> pick your database (the one named in
--   api/config.php) -> Import -> choose this file -> Go.
--
-- That is the whole database step. It replaces "import these four in this
-- exact order", which is four chances to make one mistake that fails quietly.
--
-- SAFE TO RE-RUN. Every statement is CREATE TABLE IF NOT EXISTS or an insert
-- that ignores duplicates, so importing it a second time changes nothing and
-- repairs anything missing. It does NOT delete or overwrite existing orders.
--
-- Parts, in dependency order:
${PARTS.map(([f, why], i) => `--   ${i + 1}. ${f.padEnd(18)} ${why}`).join('\n')}
`,
]

let bytes = 0
for (const [file, why] of PARTS) {
  const sql = readFileSync(join(DIR, file), 'utf8')
  for (const [re, what] of FORBIDDEN) {
    if (re.test(sql)) {
      console.error(`${file} contains ${what}. It can no longer be concatenated —`)
      console.error('fix the part file or stop generating install.mysql.sql.')
      process.exit(1)
    }
  }
  bytes += sql.length
  chunks.push(`\n\n-- ${'='.repeat(72)}\n-- ${file} — ${why}\n-- ${'='.repeat(72)}\n\n${sql.trimEnd()}\n`)
}

const out = join(DIR, 'install.mysql.sql')
writeFileSync(out, chunks.join(''))
console.log(`install.mysql.sql  ${PARTS.length} parts, ${Math.round(bytes / 1024)} kB`)

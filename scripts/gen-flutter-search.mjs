#!/usr/bin/env node
/**
 * Generates the Flutter app's search corpus and its parity fixtures.
 *   npm run flutter:search     (add --check to diff without writing)
 *
 * The native search is a hand port of `src/lib/search.ts`'s ALGORITHM —
 * tokenise, expand, score — but none of its DATA is typed twice. The documents
 * the index is built from (`buildDocs`), the synonym table, the stopwords and
 * the «elsewhere in Kuwait» list are all read out of the real module, so a
 * synonym added on the web tomorrow reaches the app on the next run instead of
 * the next time somebody remembers.
 *
 * What the port cannot inherit is behaviour, so this also records the web
 * engine's own answers for a few hundred queries to
 * `flutter_app/test/fixtures/search_parity.json`. The Dart test replays them
 * and demands the same slugs in the same order with the same scores; that is
 * the oracle, and it is the only thing that makes «a faithful port» a
 * measured claim rather than a hope.
 */
import { execSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const DART = join(ROOT, "flutter_app/lib/data/search_data.g.dart");
const FIXTURE = join(ROOT, "flutter_app/test/fixtures/search_parity.json");

const tmp = mkdtempSync(join(tmpdir(), "wain-flutter-search-"));
const entry = join(tmp, "entry.ts");
writeFileSync(
  entry,
  `export * from ${JSON.stringify(join(ROOT, "src/lib/search.ts"))};\n` +
    `export { places, categories } from ${JSON.stringify(join(ROOT, "src/lib/places.ts"))};\n`
);
const bundle = join(tmp, "entry.mjs");
execSync(
  `npx -y esbuild ${JSON.stringify(entry)} --bundle --format=esm ` +
    `--alias:@=${JSON.stringify(join(ROOT, "src"))} --outfile=${JSON.stringify(bundle)} --log-level=error`,
  { cwd: ROOT, stdio: "pipe" }
);
const S = await import(pathToFileURL(bundle).href);
rmSync(tmp, { recursive: true, force: true });

const dq = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\$/g, "\\$") + "'";
const list = (a) => `[${a.map(dq).join(", ")}]`;

const docs = S.buildDocs(S.places);
const docRows = docs
  .map(
    (d) => `  SearchDoc(
    id: ${dq(d.id)},
    kind: ${dq(d.kind)},
    title: ${dq(d.title)},
    subtitle: ${dq(d.subtitle)},
    url: ${dq(d.url)},${d.category ? `\n    category: ${dq(d.category)},` : ""}
    keywords: const ${list(d.keywords)},
    body: ${dq(d.body)},
  )`
  )
  .join(",\n");

const synRows = Object.entries(S.SYNONYMS)
  .map(([k, v]) => `  ${dq(k)}: ${list(v)},`)
  .join("\n");

const dartOut = `// GENERATED by scripts/gen-flutter-search.mjs from src/lib/search.ts.
// Do not edit: run \`npm run flutter:search\`.
library;

import 'search_doc.dart';

/// Exactly what \`buildDocs(places)\` returns on the web, in the same order.
final List<SearchDoc> kSearchDocs = [
${docRows},
];

/// \`SYNONYMS\` as written (un-normalised); search.dart folds the keys at load,
/// the way the web does.
const Map<String, List<String>> kSynonyms = {
${synRows}
};

const Set<String> kStopwords = {${[...S.STOP].map(dq).join(", ")}};

/// Already tokenised — the web builds this set through \`tokenize\`.
const Set<String> kElsewhereInKuwait = {${[...S.ELSEWHERE_IN_KUWAIT].map(dq).join(", ")}};
`;

// ── fixtures ───────────────────────────────────────────────────────────────
const names = S.places.map((p) => p.nameAr);
const plausible = ["شاورما","بيتزا","سينما","مقهى","جيم","صيدلية","مستشفى","بنك","حلويات","ايس كريم","سوشي","برجر","دجاج","عصير","فطور","سهرة","رومانسي","هدوء","واي فاي","مواقف","عوائل","شباب","رخيص","فخم","بحر","صحراء","تخييم","مشي","رياضة","أطفال","كتب","ملابس","عطور","ذهب","موبايل"];
const shisha = ["شيشة","شيشه","نرجيلة","أرجيلة","معسل","حقة","shisha","sheesha","hookah"];
const phrases = [
  "قهوة","كافيه","كافيه بالسالمية","شاطئ في الفحيحيل","أماكن في الجهراء","وين نتعشى","أبي أتغدى","أتقهوى",
  "طلعة بالصيف","مكان بارد","برا بالشتاء","مارينا كريسنت","chai","cafe","cafes","kids","seafood","cheap",
  "مچبوس","مجبوس","كبسة","چاي","چای","کرک","سمچ","أسواق","مولات","متاحف","مطعم عايلة","وين أطلع","متحف قديم",
  "السالمية","حولي","الخيران","اليران","المباركيه","المُباركية","أبراج","برج","ريوق","غبقة","كشتة","هيل","ونسة",
  "ببلاش","انستقرام","فيو","شلة","أثري","ربع","مع الربع","عيال","الجو حار","الجو حار والعيال بالسالمية",
  "بالسالمية","وبحر","للعيال","بالمول","مطعم سمك","أكل كويتي","مطاعم","تسوق","مول","سوق","حديقة","حدائق",
  "كافي","كوفي","شاي","كرك","سباحه","غروب","تصوير","إطلالة","رخيص وقريب","أحسن تقييم","الأعلى تقييماً",
  "قق","ق","","   ","the","في","أبراج الكويت","kuwait towers","Gulf Road Cafés","gulf road cafes","café",
  "Café","١٢٣","فندق","صيدلية بالسالمية","سوق شرق","شرق","مسجد","المسجد الكبير","شارع سالم المبارك",
  "الروضة","بيان","خيطان","سلوى","مشي داخلي","ممشى","تمشية","ألعاب","نلعب","الجزيرة الخضراء","فيلكا",
];
const queries = [...new Set([...names, ...plausible, ...shisha, ...phrases])];
const index = S.buildIndex(S.places);
const fixture = {
  docs: docs.length,
  cases: queries.map((q) => ({
    q,
    hits: S.search(q, index, { limit: 20 }).map((h) => ({ id: h.doc.id, score: h.score, matched: h.matched })),
  })),
};
const fixtureOut = JSON.stringify(fixture, null, 1) + "\n";

if (CHECK) {
  const same = (p, s) => existsSync(p) && readFileSync(p, "utf8") === s;
  if (!same(DART, dartOut) || !same(FIXTURE, fixtureOut)) {
    console.error("flutter search data is stale — run `npm run flutter:search`");
    process.exit(1);
  }
  console.log(`flutter search data current (${docs.length} docs, ${fixture.cases.length} parity cases)`);
} else {
  mkdirSync(dirname(FIXTURE), { recursive: true });
  writeFileSync(DART, dartOut);
  writeFileSync(FIXTURE, fixtureOut);
  console.log(`wrote ${docs.length} docs, ${Object.keys(S.SYNONYMS).length} synonyms, ${fixture.cases.length} parity cases`);
}

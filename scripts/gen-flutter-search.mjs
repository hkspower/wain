  "سائح أول مرة بالكويت", "جمعة الصبح", "سوق السمك", "وين أروح الحين", "وين نطلع", "زهقان", "ملل", "وين",
  // «داخلي» is a constraint in any month (3 October, سالم's chip).
  "قهوة داخلي", "مطعم داخلي", "مكان مكيف", "بحر داخلي", "قهوة مكيّفة رخيصة",

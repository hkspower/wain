#!/usr/bin/env node
/**
 * Generates the Flutter app's search corpus and its parity fixtures.
 *   npm run flutter:search     (add --check to diff without writing)
 *
 * The native search is a hand port of `src/lib/search.ts`'s ALGORITHM —
 * tokenise, expand, score — but none of its DATA is typed twice. The documents
 * the index is built from (`buildDocs`), the synonym table, the stopwords and
 * the «elsewhere in Kuwait» list are all read out of the real module, so a
 * synonym added on the web tomorrow reaches the app on the next run instead of
 * the next time somebody remembers.
 *
 * What the port cannot inherit is behaviour, so this also records the web
 * engine's own answers for a few hundred queries to
 * `flutter_app/test/fixtures/search_parity.json`. The Dart test replays them
 * and demands the same slugs in the same order with the same scores; that is
 * the oracle, and it is the only thing that makes «a faithful port» a
 * measured claim rather than a hope.
 */
import { execSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const DART = join(ROOT, "flutter_app/lib/data/search_data.g.dart");
const FIXTURE = join(ROOT, "flutter_app/test/fixtures/search_parity.json");

const tmp = mkdtempSync(join(tmpdir(), "wain-flutter-search-"));
const entry = join(tmp, "entry.ts");
writeFileSync(
  entry,
  `export * from ${JSON.stringify(join(ROOT, "src/lib/search.ts"))};\n` +
    `export { places, categories } from ${JSON.stringify(join(ROOT, "src/lib/places.ts"))};\n` +
    // The answer's order and words ride on the search, so they are replayed
    // with it: same documents, same hits, then the same first place and the
    // same sentences.
    `export { answerOrder } from ${JSON.stringify(join(ROOT, "src/lib/answer-order.ts"))};\n` +
    `export { GOOGLE_FIGURES } from ${JSON.stringify(join(ROOT, "src/lib/place-reviews.ts"))};\n` +
    `export { answerParts } from ${JSON.stringify(join(ROOT, "src/lib/voice-lines.ts"))};\n` +
    // سالم's memory reads a short reply against the last answer, folding words
    // with this same search's `normalise` — so it is replayed with it too.
    `export { readFollowUp, nextPlaces, followUpChips } from ${JSON.stringify(join(ROOT, "src/lib/salem-followup.ts"))};\n`
);
const bundle = join(tmp, "entry.mjs");
execSync(
  `npx -y esbuild ${JSON.stringify(entry)} --bundle --format=esm ` +
    `--alias:@=${JSON.stringify(join(ROOT, "src"))} --outfile=${JSON.stringify(bundle)} --log-level=error`,
  { cwd: ROOT, stdio: "pipe" }
);
const S = await import(pathToFileURL(bundle).href);
rmSync(tmp, { recursive: true, force: true });

const dq = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\$/g, "\\$") + "'";
const list = (a) => `[${a.map(dq).join(", ")}]`;

const docs = S.buildDocs(S.places);
const docRows = docs
  .map(
    (d) => `  SearchDoc(
    id: ${dq(d.id)},
    kind: ${dq(d.kind)},
    title: ${dq(d.title)},
    subtitle: ${dq(d.subtitle)},
    url: ${dq(d.url)},${d.category ? `\n    category: ${dq(d.category)},` : ""}
    keywords: const ${list(d.keywords)},
    body: ${dq(d.body)},
  )`
  )
  .join(",\n");

const synRows = Object.entries(S.SYNONYMS)
  .map(([k, v]) => `  ${dq(k)}: ${list(v)},`)
  .join("\n");
const tableRows = (t) =>
  Object.entries(t)

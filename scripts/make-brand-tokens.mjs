/**
 * Make the brand colour a token the shop actually reads.
 *
 *   node scripts/make-brand-tokens.mjs          # rewrite the block in sporta-ui.css
 *   node scripts/make-brand-tokens.mjs --check  # fail if it is out of date
 *
 * THE PROBLEM IT SOLVES. `--brand` exists on :root and the theme editor writes
 * it, so it looked wired. It is not: Tailwind v4 compiled the brand colour to
 * LITERAL HEX in every utility class — `.bg-brand{background-color:#e0561c}` —
 * and `var(--brand)` is read in exactly one place in the whole stylesheet, the
 * skip link. Measured 2026-09-09: 51 literal occurrences across the three
 * brand values (#e0561c ×23, #b8430f ×8, #ff7b17 ×20). So the editor's brand
 * control moved the skip link and nothing else.
 *
 * The bundle has no source here and its stylesheet is content-hashed — editing
 * it in place would pin every returning visitor, because sw.js caches hashed
 * assets cache-first and never re-asks. So the fix is a later stylesheet that
 * re-declares the same rules in terms of the token. sporta-ui.css is linked
 * AFTER index-*.css in index.html, so equal specificity is enough and no
 * !important is needed anywhere.
 *
 * WHY GENERATED RATHER THAN HAND-WRITTEN. Fifty-one occurrences across forty
 * rules, several of them long gradient shorthands, is exactly the transcription
 * a person gets subtly wrong — and worse, gets wrong again the next time the
 * bundle is rebuilt with a new class. Reading the built stylesheet and emitting
 * the block means the two cannot drift, and `--check` says so at commit time.
 *
 * WHAT IT DELIBERATELY LEAVES ALONE:
 *
 *   The DARK STOPS of the hero and tile gradients — #35200e, #2f1d10, #3d1f0c
 *   and the rest. They are near-black warm tints, not the brand swatch, and
 *   turning them into a token would need a designer to decide what a blue shop
 *   with warm-brown shadows should look like. Only the single brand-coloured
 *   glow stop in each of those rules is tokenised. So a brand change moves the
 *   glow and leaves the composition, which is the honest half of the job; the
 *   rest is a redesign and needs asking for.
 *
 *   The :root declaration and .skip-link, which are already correct.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { readdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ASSETS = resolve(HERE, '../sporta-site/public_html/assets')
const TARGET = resolve(ASSETS, 'sporta-ui.css')

const OPEN = '/* >>> brand tokens — generated by scripts/make-brand-tokens.mjs */'
const CLOSE = '/* <<< brand tokens */'

/** The three brand values, and the token each becomes. Lower case throughout:
 *  the built stylesheet is minified lower case, and a case-sensitive match that
 *  silently finds nothing is this project's most repeated mistake. */
const TOKENS = [
  ['#e0561c', '--brand'],
  ['#b8430f', '--brand-dark'],
  ['#ff7b17', '--brand-bright'],
]

const built = readdirSync(ASSETS)
  .filter((f) => /^index-.*\.css$/.test(f))
  .map((f) => readFileSync(resolve(ASSETS, f), 'utf8'))
  .join('\n')

if (!built) {
  console.error('no built stylesheet (assets/index-*.css) — nothing to read')
  process.exit(2)
}

/** Every top-level `selector{body}` in the stylesheet. Good enough because the
 *  brand values never appear inside an @media or @supports block here — and if
 *  one ever does, this finds nothing for it and the count below says so. */
const rules = [...built.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({
  sel: m[1].trim(),
  body: m[2],
}))

/** `#e0561c66` -> `color-mix(in srgb, var(--brand) 40%, transparent)`.
 *  Alpha is 8-digit hex in the built file; color-mix is how the same colour is
 *  expressed once the value is a variable, because you cannot append two hex
 *  digits to a var(). The literal is emitted first as a fallback, exactly the
 *  shape the built stylesheet itself uses when it follows a hex with lab(). */
const asVar = (hex, token, alphaHex) => {
  if (!alphaHex) return `var(${token})`
  const pct = Math.round((parseInt(alphaHex, 16) / 255) * 100)
  return `color-mix(in srgb, var(${token}) ${pct}%, transparent)`
}

const out = []
let occurrences = 0
let ruleCount = 0

for (const { sel, body } of rules) {
  // Already correct, or the declaration of the token itself.
  if (sel === ':root' || sel === '.skip-link') continue

  const low = body.toLowerCase()
  if (!TOKENS.some(([hex]) => low.includes(hex))) continue

  // Rewrite every declaration that mentions a brand value. A declaration that
  // does not is dropped: re-stating it would mean this block also owns padding
  // and border-radius it has no business owning, and any later edit to the
  // bundle's copy would be silently overridden by a stale duplicate here.
  const kept = []
  for (const decl of body.split(';')) {
    if (!decl.trim()) continue
    const dl = decl.toLowerCase()
    if (!TOKENS.some(([hex]) => dl.includes(hex))) continue

    // The built file emits `color:#e0561c80` then `color:lab(…)` for the same
    // property. Skip the lab() twin: it is the same colour said twice, and it
    // carries no hex to substitute.
    if (/lab\(/.test(dl) && !TOKENS.some(([hex]) => dl.includes(hex))) continue

    let next = decl
    for (const [hex, token] of TOKENS) {
      next = next.replace(new RegExp(hex + '([0-9a-f]{2})?', 'gi'), (_, a) => {
        occurrences++
        return asVar(hex, token, a)
      })
    }
    kept.push([decl.trim(), next.trim()])
  }

  if (!kept.length) continue
  ruleCount++
  const lines = kept.map(([literal, tokenised]) => `  ${literal};\n  ${tokenised};`)
  out.push(`${sel} {\n${lines.join('\n')}\n}`)
}

// The marker is a COMPLETE comment and the prose is a SECOND one. They were a
// single run of lines the first time — `/* >>> … */` followed by ` * DO NOT
// EDIT …` — which is not a comment at all after the first `*/`, so the parser
// threw away everything up to the next one, :root included. --brand-dark and
// --brand-bright came back empty from getComputedStyle and the theme rig said
// so. Emitting invalid CSS produces no error anywhere; only the missing value
// showed it.
const block = [
  OPEN,
  '/*',
  ' * DO NOT EDIT BY HAND — run the script. It reads the built stylesheet and',
  ' * re-states every rule that hard-codes a brand colour, in terms of the token,',
  ' * so the palette control in /backends changes the shop rather than the skip',
  ' * link alone. Each rule keeps its literal value on the line above as a',
  ' * fallback for a browser without color-mix().',
  ' *',
  ` * ${ruleCount} rules, ${occurrences} colour values, from assets/index-*.css.`,
  ' */',
  ':root {',
  '  /* Defaults, so this block is a no-op until something sets them. The two',
  '     below do not exist in the built stylesheet at all — only --brand does —',
  '     and every rule under them falls back to its literal anyway. */',
  '  --brand-dark: #b8430f;',
  '  --brand-bright: #ff7b17;',
  '}',
  ...out,
  CLOSE,
].join('\n')

const current = readFileSync(TARGET, 'utf8')
const start = current.indexOf(OPEN)
const end = current.indexOf(CLOSE)

const next =
  start === -1
    ? current.replace(/\s*$/, '\n\n') + block + '\n'
    : current.slice(0, start) + block + current.slice(end + CLOSE.length)

if (process.argv.includes('--check')) {
  const same = next === current
  console.log(
    same
      ? `ok   the brand-token block matches the built stylesheet (${ruleCount} rules, ${occurrences} values)`
      : 'FAIL the brand-token block is out of date — run node scripts/make-brand-tokens.mjs'
  )
  process.exit(same ? 0 : 1)
}

writeFileSync(TARGET, next)
console.log(`wrote ${ruleCount} rules covering ${occurrences} colour values into assets/sporta-ui.css`)

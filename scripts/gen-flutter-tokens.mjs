#!/usr/bin/env node
/**
 * Generates the Flutter app's design tokens.   npm run flutter:tokens
 *
 * `flutter_app/lib/theme/colors.dart` used to say, of its hand-copied ramps,
 * that a codegen step «would be more ceremony than the drift risk is worth».
 * That held for eight ramps. It stopped holding when the category hero and
 * tint tokens, the line weights, the radius scale, the type scale and seven
 * shadow layers all needed to match too — about 170 values, each one a place
 * for the native app to quietly stop being the same brand. So this reads
 * `src/app/theme.css`'s @theme block and writes them out, the way
 * `gen-flutter-catalogue.mjs` does for the data: generated, never retyped.
 *
 * `--check` re-renders and diffs without writing (wired into audit:flutter).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CSS = join(ROOT, "src/app/theme.css");
const OUT = join(ROOT, "flutter_app/lib/theme/tokens.g.dart");

const src = readFileSync(CSS, "utf8")
  // Comments hold colons and semicolons that would confuse the declaration split.
  .replace(/\/\*[\s\S]*?\*\//g, "");
const block = src.slice(src.indexOf("@theme"));
const decls = [...block.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)].map((m) => [m[1], m[2].trim().replace(/\s+/g, " ")]);

// A Dart identifier cannot start with a digit, and two of the theme's own names
// do (2xs, 2xl…). «s» for size/step keeps them readable: s2xs, s2xl.
const camel = (s) => {
  const c = s.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());
  return /^\d/.test(c) ? `s${c}` : c;
};
const colors = [];
const radii = [];
const texts = [];
const leadings = [];
const shadows = [];
for (const [name, value] of decls) {
  if (name.startsWith("--color-") && /^#[0-9a-f]{6}$/i.test(value)) {
    colors.push([camel(name.slice("--color-".length)), value.slice(1).toUpperCase()]);
  } else if (name.startsWith("--radius-")) {
    radii.push([camel(name.slice("--radius-".length)), remToPx(value)]);
  } else if (/^--text-[a-z0-9]+$/.test(name)) {
    texts.push([camel(name.slice("--text-".length)), remToPx(value)]);
  } else if (/^--text-[a-z0-9]+--line-height$/.test(name)) {
    leadings.push([camel(name.slice("--text-".length, -"--line-height".length)), Number(value)]);
  } else if (/^--shadow-[a-z0-9]+$/.test(name) && value.includes("rgb(")) {
    shadows.push([camel(name.slice("--shadow-".length)), value]);
  }
}
function remToPx(v) {
  const m = /^([\d.]+)rem$/.exec(v);
  if (!m) throw new Error(`theme.css: expected a rem value, got «${v}»`);
  return Number(m[1]) * 16;
}
const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));

/** `0 6px 12px -3px rgb(20 18 15 / 0.08), …` → BoxShadow list. */
function boxShadows(value) {
  // Split on commas that are not inside rgb( … ).
  const layers = value.split(/,(?![^(]*\))/).map((s) => s.trim());
  return layers
    .map((l) => {
      const m = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?(?:\s+(-?[\d.]+)px)?(?:\s+(-?[\d.]+)px)?\s+rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)$/.exec(l);
      if (!m) throw new Error(`theme.css: cannot read shadow layer «${l}»`);
      const [, x, y, blur = "0", spread = "0", r, g, b, a] = m;
      return `BoxShadow(offset: Offset(${num(+x)}, ${num(+y)}), blurRadius: ${num(+blur)}, spreadRadius: ${num(+spread)}, color: Color.fromRGBO(${r}, ${g}, ${b}, ${a}))`;
    })
    .join(",\n    ");
}

if (!colors.length || !radii.length || !texts.length || !shadows.length)
  throw new Error("theme.css: a token group came back empty — did the @theme block move?");

const out = `// GENERATED by scripts/gen-flutter-tokens.mjs from src/app/theme.css.
// Do not edit: run \`npm run flutter:tokens\`.
library;

import 'package:flutter/painting.dart';

abstract final class WainColors {
${colors.map(([n, h]) => `  static const ${n} = Color(0xFF${h});`).join("\n")}
}

abstract final class WainRadius {
${radii.map(([n, v]) => `  static const ${n} = ${num(v)};`).join("\n")}
}

/// Font sizes in logical pixels (1rem = 16). Sizes Tailwind ships with and the
/// theme does not override (xs, sm, base, lg, xl) are listed in [WainText].
abstract final class WainText {
${texts.map(([n, v]) => `  static const ${n} = ${num(v)};`).join("\n")}
  static const xs = 12.0;
  static const sm = 14.0;
  static const base = 16.0;
  static const lg = 18.0;
  static const xl = 20.0;

  /// Line-height ratios for Arabic, looser as the type gets smaller.
  static const Map<String, double> leading = {
${leadings.map(([n, v]) => `    '${n}': ${v},`).join("\n")}
  };
}

abstract final class WainShadows {
${shadows.map(([n, v]) => `  static const ${n} = <BoxShadow>[\n    ${boxShadows(v)},\n  ];`).join("\n")}
}
`;

if (process.argv.includes("--check")) {
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (have !== out) {
    console.error("flutter tokens are stale — run `npm run flutter:tokens`");
    process.exit(1);
  }
  console.log(`flutter tokens current (${colors.length} colours, ${radii.length} radii, ${texts.length} sizes, ${shadows.length} shadows)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} — ${colors.length} colours, ${radii.length} radii, ${texts.length} sizes, ${shadows.length} shadows`);
}

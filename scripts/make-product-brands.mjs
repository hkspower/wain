/**
 * Assign a brand to every product whose SLUG names one.
 *
 *   node scripts/make-product-brands.mjs            # report only
 *   node scripts/make-product-brands.mjs --write    # also write the .sql
 *
 * Writes database-sql/9-product-brands.sql, which the owner imports like any
 * other part.
 *
 * WHY THIS EXISTS. Every product card already draws a brand logo — the query
 * computes brand_has_logo, the bundle builds the URL, api.php serves the
 * image — and not one of the 46 products names a brand, so the whole path is
 * dead. db-audit.php reports it on every run. This does the half that can be
 * done from evidence.
 *
 * ---------------------------------------------------------------------------
 * WHAT COUNTS AS EVIDENCE, AND WHAT DOES NOT
 *
 * A product is assigned ONLY when its slug contains the brand's slug as a
 * WHOLE WORD. `vanquish-t-shirt-white` is Vanquish because the word is there;
 * that is a fact about the catalogue, not a guess about the shop.
 *
 * WORD BOUNDARIES, NOT SUBSTRINGS, and the reason is sitting in the brands
 * table: one of the eight brand slugs is `ate`. A substring match would put
 * every "skateboard", "gate", "plate" and "ultimate" under that label, and it
 * would look right in a report because the count would be plausible.
 *
 * ON TODAY'S CATALOGUE IT CHANGES NOTHING — checked, rather than claimed: no
 * product slug contains a brand slug except as a whole word, so a substring
 * match would give the same five. The guard is precautionary and stays,
 * because the next thing added to this shop is as likely to be a skate deck as
 * anything else, and a mislabelled product is a claim the shop is making to a
 * customer.
 *
 * WHAT IT DELIBERATELY DOES NOT DO:
 *
 *   Denver Nuggets is an NBA team and `nba` is a brand here — but the slug
 *   says `denver-nuggets-cap-navy`, not `nba`. Assigning it needs the
 *   knowledge that the Nuggets play in the NBA, which is true and is still an
 *   inference about how this shop labels licensed goods.
 *
 *   Cagliari Calcio and the Cheetahs are a football club and a rugby team.
 *   Neither is one of the eight brands, and inventing a ninth is not this
 *   script's business.
 *
 *   Sculpt, Define and Cloudsoft are product LINES. Two of those three are
 *   real Gymshark ranges in the world, and scripts/mock-admin.py even guesses
 *   `gymshark` for cloudsoft in its fixture — but a test fixture's guess is
 *   not evidence about a real catalogue, and twenty-seven garments is far too
 *   many to label on a hunch.
 *
 * Those are listed for the owner rather than assigned. A brand on a product is
 * a claim the shop makes to its customers; a script should only make the ones
 * that are already written down.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const WRITE = process.argv.includes('--write')
const OUT = new URL('../sporta-site/database-sql/9-product-brands.sql', import.meta.url)

const sql = (q) =>
  execFileSync('mariadb', ['-uroot', 'sporta', '-N', '-B', '-e', q], { encoding: 'utf8' }).trim()

const brands = sql('select slug from brands order by sort').split('\n').filter(Boolean)
const products = sql('select slug, category, coalesce(brand_slug, "") from products order by category, slug')
  .split('\n').filter(Boolean).map((l) => { const [slug, category, brand] = l.split('\t'); return { slug, category, brand } })

// WHOLE SEGMENTS of the slug, never a substring. See the note above about `ate`.
const brandOf = (slug) => {
  const words = new Set(slug.split('-'))
  return brands.find((b) => words.has(b)) ?? null
}

const named = []
const unnamed = []
for (const p of products) {
  const b = brandOf(p.slug)
  if (b) named.push({ ...p, want: b })
  else unnamed.push(p)
}

console.log(`${products.length} products, ${brands.length} brands\n`)
console.log(`--- named by their own slug (${named.length})`)
for (const p of named) console.log(`  ${p.want.padEnd(12)} ${p.slug}`)

// Group what is left by its first word — the product LINE — because that is
// how the owner will answer: not garment by garment, but "all the Sculpt ones".
const families = new Map()
for (const p of unnamed) {
  const fam = p.slug.split('-')[0]
  if (!families.has(fam)) families.set(fam, [])
  families.get(fam).push(p)
}
console.log(`\n--- no brand in the slug (${unnamed.length}), grouped by line`)
for (const [fam, list] of [...families.entries()].sort((a, b) => b[1].length - a[1].length)) {
  console.log(`  ${String(list.length).padStart(2)}  ${fam.padEnd(16)} ${list[0].category}${list.length > 1 ? ' …' : ''}`)
}

if (!named.length) { console.log('\nnothing to write'); process.exit(0) }

const esc = (s) => s.replace(/'/g, "''")
const body = `-- Sporta — which brand each product belongs to.
--
-- GENERATED by scripts/make-product-brands.mjs. Safe to re-run: each statement
-- names one slug and sets one column, so importing twice changes nothing.
--
-- ONLY THE PRODUCTS WHOSE SLUG SAYS SO. ${named.length} of ${products.length}. A brand on a
-- product is a claim the shop makes to its customers, and the rest of the
-- catalogue does not say which brand it belongs to — those are listed at the
-- end of this file for somebody who knows the answer.
--
-- WHAT THIS TURNS ON. Every product card already draws a brand logo and the
-- path has been dead because no product named a brand. After this, the ${named.length}
-- below will show their brand's logo — once that brand HAS one. The logos go
-- in public_html/images/<slug>/logo.png, cut out, on a transparent background;
-- scripts/image-audit.mjs refuses one that is not.

set names utf8mb4;

${named.map((p) => `update products set brand_slug = '${esc(p.want)}' where slug = '${esc(p.slug)}';`).join('\n')}

-- ---------------------------------------------------------------------------
-- STILL UNASSIGNED (${unnamed.length}). Nothing in these slugs names one of the eight
-- brands. Grouped by product line, because that is how they will be answered.
--
${[...families.entries()].sort((a, b) => b[1].length - a[1].length)
  .map(([fam, list]) => `--   ${String(list.length).padStart(2)}  ${fam.padEnd(16)} e.g. ${list[0].slug}`).join('\n')}
--
-- To assign a line once the answer is known, one statement does all of it:
--
--   update products set brand_slug = 'gymshark' where slug like 'sculpt-%';
`

if (WRITE) {
  writeFileSync(OUT, body)
  console.log(`\nwrote database-sql/9-product-brands.sql — ${named.length} assignment(s)`)
} else {
  console.log(`\n(report only — pass --write to produce database-sql/9-product-brands.sql)`)
}
